def add(table, section, d):
    """Add entries to a my_formulas table in memory; refuse to change an existing value."""
    for k, v in d.items():
        if k in table and table[k] != v:
            raise F.Miss(f"{section}: would change {k}: {table[k]} -> {v}")
        table[k] = v
        NEW.setdefault(section, {})[k] = v


