# ===================================================================================== tokenizer for the openings
JH_RE = re.compile(r"(?P<o>paṭhama|dutiya|tatiya|catuttha|pañcama)ṃ jhānaṃ")
SEP_RE = re.compile(r" ?…pe… ?|, | – | ")
VAR_AT = re.compile(r" (\[[^\]]+\])")


class Tok:
    def __init__(self, my, role, pali):
        self.my, self.role, self.pali, self.var, self.sep = my, role, pali, "", ""


def tokens(s, tables, allow_jh=False):
    """Split an opening fragment into known phrases; each Tok keeps its variant and the Pāli separator after it."""
    keys = sorted(((k, v, r) for r, tab in tables for k, v in tab.items()), key=lambda x: -len(x[0]))
    out, pos = [], 0
    while pos < len(s):
        tok = None
        for k, v, r in keys:
            e = pos + len(k)
            if s.startswith(k, pos) and (e == len(s) or s[e] in " ,…"):
                tok, pos = Tok(v, r, k), e
                break
        if tok is None and allow_jh:
            m = JH_RE.match(s, pos)
            if m and (m.end() == len(s) or s[m.end()] in " ,…"):
                tok, pos = Tok(ordj(m["o"]), "jh", m[0]), m.end()
        if tok is None:
            raise F.Miss("opening phrase: " + s[pos:pos + 90])
        m = VAR_AT.match(s, pos)
        if m:
            tok.var, pos = F.var_my(m[1]), m.end()
        m = SEP_RE.match(s, pos)
        if m:
            tok.sep, pos = m[0], m.end()
        elif pos < len(s):
            raise F.Miss("opening separator: " + s[pos:pos + 60])
        out.append(tok)
    return out


def sep_my(sep, nxt):
    """Burmese for the Pāli separator between two phrases; nxt = role of the next phrase («jh» = the jhāna noun)."""
    if "…pe…" in sep:
        return F.PE + " "
    if sep == ", ":
        return F.COMMA + " "
    if sep == " – ":
        return " – "
    if sep == " ":
        return " " if nxt == "jh" else F.COMMA + " "
    if sep == "":
        return " "
    raise F.Miss("separator: " + sep)


def tmy(t):
    return t.my + (" " + t.var if t.var else "")


def join(toks, last_role):
    """Join phrases with Burmese separators; the separator after the last one leads to a phrase of last_role."""
    out = ""
    for i, t in enumerate(toks):
        out += tmy(t) + sep_my(t.sep, toks[i + 1].role if i + 1 < len(toks) else last_role)
    return out


def pre_tok(m):
    """«ajjhattaṃ arūpasaññī bahiddhā rūpāni passati ADJ…[,] tāni abhibhuyya jānāmi passāmīti»."""
    adj = tokens(m["adj"], [("adj", ADJ)])
    a = join(adj, "end").rstrip()
    c = F.COMMA if m["c"] else ""
    return f"{ARUPASANNI} {a} {RUPANI_PASSATI}{c} {TANI_ABHIBHUYYA}"


PRE_RE = re.compile(r"ajjhattaṃ arūpasaññī bahiddhā rūpāni passati (?P<adj>[^,]+?)(?P<c>,)? "
                    r"tāni abhibhuyya jānāmi passāmīti(?= )")


def jhana_open(head_my, rest):
    """HEAD + «[PRE] FORMULA LASTJH upasampajja viharati [Q]» -> Burmese time clause."""
    m = re.fullmatch(r"(?P<f>.+?) upasampajja viharati(?: (?P<q>.+))?", rest)
    if not m:
        raise F.Miss("no «upasampajja viharati»: " + rest[:80])
    f, toks = m["f"], []
    pm = PRE_RE.match(f)
    if pm:
        t = Tok(pre_tok(pm), "f", pm[0])
        t.sep = " "
        toks.append(t)
        f = f[pm.end() + 1:]
    else:
        for k, v in PRE_FIXED.items():
            if f.startswith(k + " "):
                t = Tok(v, "f", k)
                t.sep = " "
                toks.append(t)
                f = f[len(k) + 1:]
                break
    toks += tokens(f, [("f", FORM), ("qadj", QADJ)], allow_jh=True)
    last = toks.pop()
    if last.role != "jh":
        raise F.Miss("opening does not end in a jhāna: " + rest[:80])
    qadj = [t for t in toks if t.role == "qadj"]
    ftoks = [t for t in toks if t.role != "qadj"]
    for t in qadj:
        t.sep = " "
    q = qadj + (tokens(m["q"], [("q", QTAB)]) if m["q"] else [])
    seq = ftoks + q
    body = join(seq, "jh") if seq else ""
    var = (" " + last.var) if last.var else ""
    return f"{head_my}{sep_my(' ', 'f')}{body}{last.my}ကို{var} {UPAS} {YASMIM}"


LOK_RE = re.compile(r"(?P<series>(?:lokuttaraṃ \S+ bhāveti…pe… )*)lokuttaraṃ (?P<x>\S+) bhāveti "
                    r"niyyānikaṃ apacayagāmiṃ (?P<purp>.+? bhūmiyā pattiyā) (?P<rest>.+)")


def lok_x(x):
    if x not in LOKX:
        raise F.Miss("lokuttaraṃ X: " + x)
    return f"{LOK} {LOKX[x]}{BHAVETI}"


def r_open(m):
    body = m["body"]
    mk = re.fullmatch(r"kāmāvacaraṃ kusalaṃ cittaṃ uppannaṃ hoti (?P<q>.+)", body)
    if mk:
        q = tokens(mk["q"], [("q", QTAB)])
        return (f"{join(q, 'end').rstrip()} {F.CITTA_KIND['kāmāvacaraṃ kusalaṃ cittaṃ']}သည် "
                f"{F.UPPANNA} {YASMIM}")
    for k, v in HEADS.items():
        if body.startswith(k + " "):
            return jhana_open(v, body[len(k) + 1:])
    ml = LOK_RE.fullmatch(body)
    if ml:
        series = "".join(lok_x(x) + F.PE + " " for x in re.findall(r"lokuttaraṃ (\S+) bhāveti…pe… ", ml["series"]))
        if ml["purp"] not in PURPOSE:
            raise F.Miss("purpose: " + ml["purp"])
        head = f"{series}{PURPOSE[ml['purp']]}၊ {NIYY_APAC}၊ {lok_x(ml['x'])}"
        return jhana_open(head, ml["rest"])
    raise F.Miss("opening: " + body[:100])


OPEN_RE = re.compile(r"Yasmiṃ samaye (?P<body>(?:(?!ārammaṇaṃ vā|tasmiṃ samaye).)+?)(?=(?:, | – | )tasmiṃ samaye)")


