def write(name, txt):
    txt = unicodedata.normalize("NFC", txt)
    (OUT / name).write_text(txt, encoding="utf-8")
    print(f"wrote {name}: {sum(1 for l in txt.splitlines() if l)} lines")


def chapter(key):
    name = CHAPTERS[key]
    write(name, F.translate_cu((PALI / name).read_text(encoding="utf-8-sig")))


def write_terms():
    L = [MARK, "", "One «Pāli = Burmese» per line, generated from the in-memory additions of make_ch2-04-05.py "
                   "(my_formulas.py and my-zeroshot-terms.md are not edited).", ""]
    for sec, d in NEW.items():
        L += [f"### {sec}", ""] + [f"{p} = {m}" for p, m in d.items()] + [""]
    txt = NOTES.read_text(encoding="utf-8") if NOTES.exists() else ""
    i = txt.find(MARK)
    base = (txt[:i] if i >= 0 else txt).rstrip("\n") + "\n\n"
    NOTES.write_text(unicodedata.normalize("NFC", base + "\n".join(L).rstrip("\n") + "\n"), encoding="utf-8")
