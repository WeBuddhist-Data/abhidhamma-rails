def tokens(seg):
    w, i, out = seg.split(" "), 0, []
    while i < len(w):
        for k in range(ROLE_MAX, 0, -1):
            if i + k > len(w):
                continue
            key = " ".join(w[i:i + k])
            key = key[0].lower() + key[1:]
            if key in ROLE:
                out.append((ROLE[key][0], key, ROLE[key][1]))
                i += k
                break
        else:
            raise F.Miss("opening word: " + w[i] + "  in: " + seg[:120])
    return out


def qchain(qs):
    return "၍ ".join(qs) + "သော"


def seg_jhana(tk):
    roles = "".join({"pre": "P", "jh": "J", "verb": "V", "q": "Q", "qn": "N", "k": "K"}[r] for r, _, _ in tk)
    if not re.fullmatch(r"P*(?:J?V?)(?:Q*N?K?)", roles) or ("V" in roles and "J" not in roles) or \
            (("N" in roles) != ("K" in roles)):
        raise F.Miss("jhāna segment order: " + " ".join(p for _, p, _ in tk))
    parts = [m for r, _, m in tk if r == "pre"]
    qs = [m for r, _, m in tk if r in ("q", "qn")]
    jh = [m for r, _, m in tk if r == "jh"]
    k = [m for r, _, m in tk if r == "k"]
    x = qchain(qs) if qs else ""
    if jh:
        x = (x + " " if x else "") + jh[0] + (f"ကို {ENTER}သော" if "V" in roles else "")
    if k:
        x += " " + k[0]
    if x:
        parts.append(x)
    return " ".join(parts)


def objs_my(tk):
    """objects (with vā) and «yaṃ yaṃ vā panārabbha» of one segment, joined as in the model (r_open)."""
    return (COMMA + " ").join(m for r, _, m in tk if r in ("objv", "yam"))


def open_my(s):
    """A resultant / functional / jhāna opening, from «Yasmiṃ samaye» (or «Tasseva») up to «, tasmiṃ samaye»."""
    body = s[len("Yasmiṃ samaye "):] if s.startswith("Yasmiṃ samaye ") else s
    if "viharati, " in body:
        SLIPS.append("comma after «viharati» inside an opening: " + body[:60])
        body = body.replace("viharati, ", "viharati ")
    segs = [tokens(x) for x in re.split(r"\s*…pe…\s*", body)]
    R = [{r for r, _, _ in t} for t in segs]
    citta = "kind" in R[0]
    if citta and "objv" in R[0] and all(r <= {"objv", "yam"} for r in R[1:]):
        # model order (r_open): objects first, then qualifiers, then «KIND-သည် … ဖြစ်ပေါ်လာသော»; the «…pe…» stays
        # inside the object list
        t0 = segs[0]
        pre = [m for r, _, m in t0 if r == "pre"]
        objs = (PE + " ").join(objs_my(t) for t in segs)
        quals = (COMMA + " ").join(m for r, _, m in t0 if r == "qual")
        adv = "".join(m + " " for r, _, m in t0 if r == "adv")
        vip = "".join(m + " " for r, _, m in t0 if r == "vip")
        kind = [m for r, _, m in t0 if r == "kind"][0]
        if [r for r, _, _ in t0 if r not in ("pre",)][:3] not in (["vip", "kind", "upp"], ["kind", "upp", "qual"]):
            raise F.Miss("citta opening: " + body[:100])
        out = (" ".join(pre) + " " if pre else "") + f"{objs} {quals} {vip}{kind}သည် {adv}{F.UPPANNA}"
    elif citta:
        parts, pending = [], False
        for t in segs:
            rs = [r for r, _, _ in t]
            pre = [m for r, _, m in t if r == "pre"]
            quals = (COMMA + " ").join(m for r, _, m in t if r == "qual")
            adv = " ".join(m for r, _, m in t if r == "adv")
            obj = [m for r, _, m in t if r == "obj"]
            if "kind" in rs:
                vip = "".join(m + " " for r, _, m in t if r == "vip")
                kind = [m for r, _, m in t if r == "kind"][0]
                if obj:          # «KIND uppannaṃ hoti QUAL X-ārammaṇaṃ»: one full clause per segment
                    x = (" ".join(pre) + " " if pre else "") + f"{obj[0]}{COMMA} {quals} {vip}{kind}သည် {F.UPPANNA}"
                else:            # the qualifier chain follows in the next segments; the verb comes at the end
                    x = (" ".join(pre) + " " if pre else "") + f"{vip}{kind}သည် {quals}" + (" " + adv if adv else "")
                    pending = True
            else:
                if not set(rs) <= {"qual", "adv", "objv", "yam"}:
                    raise F.Miss("qualifier segment: " + " ".join(p for _, p, _ in t))
                x = " ".join(y for y in (quals, adv, objs_my(t)) if y)
                if "yam" in rs and pending:
                    x += " " + F.UPPANNA
                    pending = False
            parts.append(x)
        if pending:
            raise F.Miss("citta opening without its verb: " + body[:100])
        out = (PE + " ").join(parts)
    else:
        out = (PE + " ").join(seg_jhana(t) for t in segs)
    if out.endswith("၍"):
        raise F.Miss("opening ends in a verb chain: " + body[-80:])
    return out + (" " if out.endswith("သော") else " ဖြစ်သော ") + F.YASMIM


