def line_my(body):
    m = F.HEAD_RE.fullmatch(body)
    if m:
        h = HEAD5.get(m["t"]) or F.HEAD.get(m["t"])
        if not h:
            raise Miss("heading: " + body)
        return f"{m['h']} {h}"
    out = []
    for snt in split_sentences(body):
        end = snt[-1]
        if end not in ".?":
            raise Miss("sentence end: " + snt)
        core = snt[:-1]
        if core in COLO5:
            out.append(COLO5[core] + F.END)
        else:
            out.append(sentence_my(core) + F.END)
    return " ".join(out)


def translate(text):
    out = []
    for line in text.splitlines():
        if not line.strip():
            out.append("")
            continue
        m = F.ID_RE.search(line)
        body = line[:m.start()] if m else line
        out.append(line_my(body) + (" " + m.group(1) if m else ""))
    return "\n".join(out).rstrip("\n") + "\n"


