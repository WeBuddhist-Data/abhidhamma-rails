def case_sfx(case, num, th):
    s = ""
    if case == "loc":
        s = LOC
    elif case == "acc" and num == "pl":
        s = "တို့"
    if th:
        s += THAP
    return s


def noun_val(key, count=False):
    k = lowfirst(key)
    if count and k in CNT:
        return CNT[k], "", "pl"
    return N[k]


def np_my(s):
    """A list of noun phrases / fragments (Pāli) -> Burmese, left to right."""
    pos, out = 0, []
    while pos < len(s):
        for p, my in SEPS:
            if s.startswith(p, pos):
                out.append(my)
                pos += len(p)
                break
        else:
            m = FX_RE.match(s, pos)
            mj = JH_RE.match(s, pos)
            mt = PRE_TH_RE.match(s, pos)
            mn = NUMNOUN_RE.match(s, pos)
            mo = NOUN_RE.match(s, pos)
            mb = NUM_RE.match(s, pos)
            mv = re.compile(r"\[[^\]]+\]").match(s, pos)
            cands = []
            if m:
                cands.append((m.end(), "fx", m))
            if mj:
                cands.append((mj.end(), "jh", mj))
            if mt:
                cands.append((mt.end(), "th", mt))
            if mn:
                cands.append((mn.end(), "nn", mn))
            if mo:
                cands.append((mo.end(), "n", mo))
            if mb:
                cands.append((mb.end(), "num", mb))
            if mv:
                cands.append((mv.end(), "var", mv))
            if not cands:
                raise Miss("np: " + s[pos:pos + 90])
            end, kind, mm = max(cands, key=lambda c: c[0])      # longest match wins
            if kind == "fx":
                out.append(FX[lowfirst(mm[0])])
            elif kind == "jh":
                out.append(r_jh(mm))
            elif kind == "th":
                x, c, nu = noun_val(mm["x"])
                out.append(x + case_sfx(c, nu, True))
            elif kind == "nn":
                x, c, nu = noun_val(mm["x"], count=True)
                out.append(f"{x} {cnt(NUMV[mm['num'].lower()])}" + (CA if mm["ca"] else "")
                           + case_sfx(c, "pl", bool(mm["th"])))
            elif kind == "n":
                x, c, nu = noun_val(mm["x"])
                out.append(x + (CA if mm["ca"] else "") + case_sfx(c, nu, bool(mm["th"])))
            elif kind == "num":
                out.append(cnt(NUMV[mm["num"].lower()]))
            elif kind == "var":
                if mm[0] not in VARS:
                    raise Miss("variant: " + mm[0])
                out.append(VARS[mm[0]])
            pos = end
    return "".join(out)


