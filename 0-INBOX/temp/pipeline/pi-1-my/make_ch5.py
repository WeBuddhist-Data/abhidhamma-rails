def term_my(t):
    """A Mātikā term (Pāli nominative surface) -> its approved Burmese attributive string."""
    t = SG.get(t, t)
    if t in T:
        return T[t]
    if t in PAIRS:
        x, y = PAIRS[t]
        return f"{T[x]} {F.DHAMMA_AMONG} {T[y]}"
    m = re.fullmatch(r"(?P<x>.+?) ceva (?P<y>.+?) ca", t)
    if m and (m["x"], m["y"]) in F.CEVA:
        return F.CEVA[(m["x"], m["y"])]
    m = re.fullmatch(r"(?P<y>.+?) ceva (?:no|na) ca (?P<x>.+?)", t)
    if m and (m["y"], m["x"]) in F.CEVANO:
        return F.CEVANO[(m["y"], m["x"])]
