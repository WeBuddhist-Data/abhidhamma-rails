def subj_mark(my, plural):
    if my.endswith(CA):
        return my
    return my + ("တို့သည်" if plural else "သည်")


def upp_my(s):
    """One or more «SUBJ LOC … uppajjati» clauses (1465 and 1503 run several without a full stop)."""
    parts = re.split(r"(?<=uppajjati)(, | )(?=\S)", s)
    out = []
    for i in range(0, len(parts), 2):
        m = UPP_RE.fullmatch(parts[i])
        if not m:
            raise Miss("uppajjati: " + parts[i][:90])
        subj = np_my(m["s"])
        plural = len(re.findall(SUBJ9_ALT, m["s"])) > 1
        out.append(subj_mark(subj, plural) + np_my(m["r"]) + " " + UPAJJ[m["v"]])
        if i + 1 < len(parts):
            out.append(F.COMMA + " ")
    return "".join(out)


def body_my(s):
    """A clause that is not a question / closer: «uppajjati» clauses or a noun-phrase list."""
    if re.search(r"\buppajja(?:ti|nti)$", s) and not s.lower().startswith("yattha"):
        return upp_my(s)
    return np_my(s)


def vatt_subject(s):
    """Subject of «… na vattabbā»: «X dhammā» (a Mātikā term) or a noun phrase; returns (Burmese, singular)."""
    m = re.fullmatch(r"(?P<x>.+?) ca (?P<y>.+?) ca dhammā", s)
    if m:
        return f"{term_np(lowfirst(m['x']))}{CA} {term_np(m['y'])}{CA}", False
    m = re.fullmatch(r"(?P<x>.+) dhammā", s)
    if m:
        return subj_mark(term_np(lowfirst(m["x"])), False), False
    return subj_mark(np_my(s), False), True


def sentence_my(s):
    """One Pāli sentence without its final «.» / «?» -> Burmese without «။»."""
    m = re.fullmatch(r"Katame dhammā (?P<t>.+?)(?P<pe>…pe…)?", s)
    if m:
        return f"{term_np(m['t'])} {QPL}" + (F.PE if m["pe"] else "")
    if " – ime dhammā " in s:
        subj, pred = s.rsplit(" – ime dhammā ", 1)
        if pred in PRED_NOUN:
            return f"{body_my(subj)} – {IME} {T[pred]} {COP['pl']}"
        return f"{body_my(subj)} – {IME} {pred_my(pred)}"
    m = SUBJ5_RE.fullmatch(s)
    if m:
        sg = m["s"] in SUBJ5_SG
        subj = np_my(m["s"])
        return f"{subj_mark(subj, False)} {pred_my(m['p'], sg)}"
    m = re.fullmatch(r"(?P<s>.+?) na vattabb(?P<g>ā|o|aṃ)(?P<d> –)? (?P<l>.+)", s)
    if m:
        subj, sg = vatt_subject(m["s"])
        sg = sg or m["g"] != "ā"
        return f"{subj}{' –' if m['d'] else ''} {ti_items(m['l'], sg)} {VATT}"
    m = TEVA_RE.fullmatch(s)
    if m:
        sg = m["p"] == "So eva"
        return f"ထို {TEVA_N[m['n']]}{'' if sg else 'များ'}သည်ပင် {term_np(m['t'], sg)} {COP['sg' if sg else 'pl']}"
    if lowfirst(s) in FX:
        return FX[lowfirst(s)]
    return body_my(s)


def split_sentences(line):
    """Split a line at «. » / «? » outside brackets; keep the end mark."""
    out, depth, start = [], 0, 0
    for i, ch in enumerate(line):
        if ch == "[":
            depth += 1
        elif ch == "]":
            depth -= 1
        elif ch in ".?" and depth == 0 and (i + 1 == len(line) or line[i + 1] == " "):
            out.append(line[start:i + 1])
            start = i + 2
    if start < len(line):
        out.append(line[start:])
    return out


