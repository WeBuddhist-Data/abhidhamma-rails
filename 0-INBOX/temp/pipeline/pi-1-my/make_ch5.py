def ti_items(s, sg):
    """«A-tipi, B-tipi, C-tipi» / «A-ti» -> «A …ဟုလည်းကောင်း၊ B …ဟုလည်းကောင်း» / «A …ဟု»."""
    parts = s.split(", ")
    out = []
    for p in parts:
        m = re.fullmatch(r"(?P<t>.+?)ti(?P<pi>pi)?", p)
        if not m:
            raise Miss("ti item: " + p)
        t = m["t"]
        if t.endswith("n"):
            t = t[:-1] + "ṃ"
        if t.endswith(" cā"):
            t = t[:-1] + "a"
        if t == "ya vedanāya sampayuttā":          # source slip for «adukkhamasukhāya vedanāya sampayuttā»
            t = "adukkhamasukhāya vedanāya sampayuttā"
        out.append(term_np(t, sg) + (TIPI if m["pi"] else TI))
        if bool(m["pi"]) != (len(parts) > 1):
            raise Miss("ti / tipi: " + s)
    return (F.COMMA + " ").join(out)


def pred_my(s, sg=False):
    """Predicate clauses after the subject: [siyā] TERM | [siyā] na TERM | [siyā] na vattabbā A-tipi, …"""
    nn = "sg" if sg else "pl"
    pos, out = 0, []
    while pos < len(s):
        siya = s.startswith("siyā ", pos)
        if siya:
            pos += 5
        pre = SIYA + " " if siya else ""
        m = re.compile(r"na vattabb(?:ā|o|aṃ) ").match(s, pos)
        if m:
            out.append(pre + ti_items(s[m.end():], sg) + " " + VATT)
            break
        m = TERM_RE.match(s, pos)
        neg = False
        if not m and s.startswith("na ", pos):
            m = TERM_RE.match(s, pos + 3)
            neg = True
        if not m:
            raise Miss("predicate: " + s[pos:pos + 80])
        t = m[0]
        noun = T[t] if t in PRED_NOUN else term_np(t, sg)
        out.append(pre + noun + " " + (NCOP[nn] if neg else COP[nn]))
        pos = m.end()
        for sep in (", ", "; ", " "):
            if s.startswith(sep, pos):
                out.append(F.COMMA + " ")
                pos += len(sep)
                break
    return "".join(out)


