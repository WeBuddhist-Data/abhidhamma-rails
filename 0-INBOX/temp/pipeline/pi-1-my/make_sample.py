"""Burmese zero-shot sample of pi-1 (Dhammasaṅgaṇī, «သဘောတရားများကို စုစည်းရေတွက်ခြင်း»): preamble, 1-matika.

usage: python3 -I -X utf8 make_sample.py [chapter ...] [--terms]
Every line is generated from the Pāli source by my_formulas.translate() through the tables and patterns of
my_formulas.py; a line that no rule or table entry matches stops the run (my_formulas.Miss), it is never guessed.
Each chapter is written as soon as it is complete. --terms (also run by default with no chapter argument)
rewrites my-zeroshot-terms.md from the tables.
Model for later chapters: copy this file, put your additions in a tables module (TERMS / SUT / HEAD / COLO /
VAR_KIND entries or EXTRA_RULES), and change NAMES_OUT.
"""
import pathlib
import sys
import unicodedata

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import my_formulas as F  # noqa: E402

ROOT = HERE.parents[3]
PALI = ROOT / "AI_translation/pali/pi-1_split_chapters"
OUT = ROOT / "AI_translation/burmese/pi-1-burmese-plain-zeroshot_split_chapters"
NAMES_OUT = ["preamble.md", "1-matika.md"]


def write(name, txt):
    txt = unicodedata.normalize("NFC", txt)
    (OUT / name).write_text(txt, encoding="utf-8")
    print(f"wrote {name}: {sum(1 for l in txt.splitlines() if l)} lines")


def preamble():
    name = "preamble.md"
    src = (PALI / name).read_text(encoding="utf-8-sig")
    rep = {"Namo tassa bhagavato arahato sammāsambuddhassa": F.NAMO, "# Abhidhammapiṭake": "# " + F.ABHI,
           "## Dhammasaṅgaṇīpāḷi": "## " + F.TITLE}
    out = []
    for line in src.splitlines():
        m = F.ID_RE.search(line)
        t = line[:m.start()] if m else line
        if t.strip():
            if t not in rep:
                raise F.Miss("preamble: " + t)
            t = rep[t]
        out.append(t + (" " + m.group(1) if m else ""))
    write(name, "\n".join(out).rstrip("\n") + "\n")


def chapter(name):
    write(name, F.translate((PALI / name).read_text(encoding="utf-8-sig")))


def write_terms():
    L = ["# pi-1 Burmese zero-shot: formulas and terms («Pāli = Burmese»)", "",
         "Generated by make_sample.py from my_formulas.py (sample: preamble + 1-matika). For the user's review; "
         "once approved, the core terms go into burmese-style.md. A mātikā term is shown in its attributive form "
         "(before «သဘောတရားများ»).", ""]
    L += ["## Book frame", "", f"Namo tassa bhagavato arahato sammāsambuddhassa = {F.NAMO}",
          f"Abhidhammapiṭake = {F.ABHI}", f"Dhammasaṅgaṇīpāḷi = {F.TITLE}", f"…pe… / …Pe… = {F.PE}",
          f"niṭṭhitā = {F.NITTHITA}", f"(statement end) . = {F.END}", ""]
    L += ["## dhamma and core terms", "",
          f"dhamma (phenomenon, state) = {F.DHAMMA}; dhammā (after a term) = {F.DHAMMA_PL}",
          f"dhammesu = {F.DHAMMA_LOC}; X kho pana dhammā = {F.KHO_PANA} X {F.DHAMMA_AMONG}",
          f"kusala = {F.TERMS['kusalā']}", f"akusala = {F.TERMS['akusalā']}",
          f"abyākata = {F.TERMS['abyākatā']}",
          f"hetu (root) = {F.ROOT}", f"citta = {F.MIND}", f"vedanā = {F.FEEL}",
          f"sukha / dukkha = {F.SUKHA} / {F.DUKKHA} (adjective), {F.SUKHA}မှု (noun)",
          f"vitakka = {F.VIT}", f"vicāra = {F.VIC}", f"upādāna = {F.UPA}", f"kilesa = {F.KIL}",
          f"upādiṇṇa = {F.KAMMA_BORN}သော", f"ārammaṇa (object) = အာရုံ; -ārammaṇa = X{F.TAKES}",
          f"dassanena = {F.DASS}", f"bhāvanāya = {F.BHAV}", f"pahātabba = {F.PAH} / {F.PAH_S} (before မဟုတ်)",
          f"padhāna = {F.PADHANA}", f"saṃvega = {F.SAMVEGA}", f"mātikā = {F.MATIKA}", ""]
    L += ["## Numbers and item letters", "", f"tika (triad) = {F.TIKA}", f"duka (dyad) = {F.DUKA}"]
    L += [f"{p} = {m}" for p, m in F.NUM.items()] + [f"{p} = {m}" for p, m in F.ORD.items()]
    L += [f"{p} = {m}" for p, m in F.LABEL.items()] + [""]
    L += ["## Dyad and triad patterns", "",
          f"(Ka) X dhammā. = (က) X {F.DHAMMA_PL}{F.END}",
          f"X-sampayuttā = N{F.SAMP}", f"X-vippayuttā = N{F.VIPP}",
          f"X-sahagatā = N{F.TOGETHER}", f"X-ārammaṇā = N{F.TAKES}",
          f"(cluster) X dhammā = N{F.IS}; no / na X = N{F.ISNOT}",
          f"(cluster) sa-X / X-iya (object of X) = N{F.OBJ}; a-X-iya / an-X = N{F.NOBJ}",
          f"X ceva dhammā X-iya ca = N-လည်း ဖြစ်၊ N{F.OBJ_HI} {F.DHAMMA_PL}",
          f"X-iya ceva dhammā no ca X = N၏ အာရုံ ဖြစ်နိုင်သော်လည်း N{F.ISNOT} {F.DHAMMA_PL}",
          f"X ceva dhammā X-sampayuttā ca = N-လည်း ဖြစ်၊ N{F.SAMP_HI} {F.DHAMMA_PL}",
          f"X-sampayuttā ceva dhammā no ca X = Nနှင့် ယှဉ်တွဲသော်လည်း N{F.ISNOT} {F.DHAMMA_PL}",
          f"X kho pana dhammā Y-pi. = {F.KHO_PANA} X {F.DHAMMA_AMONG} Y(…သည်တို့){F.PI}{F.END}",
          f"(Kha) Y-pi. = Y(…သည်တို့){F.PI}{F.END}",
          "free na / no / neva before a term = … (သည်) မဟုတ်; privative a- / an- = မ + verb",
          "neva A na B = A-လည်း … မဟုတ်၊ B-လည်း … မဟုတ်သော; a-A-a-B = A-လည်း မ…၊ B-လည်း မ…သော",
          f"X ca. / Xñca. (suttantika) = X{F.END} (the listing «ca» is not rendered)", ""]
    keys = list(F.TERMS)
    cut = keys.index("anidassanaappaṭighā") + 1          # TERMS lists the 22 triads first
    L += ["## Triads (attributive form)", ""] + [f"{p} = {F.TERMS[p]}" for p in keys[:cut]]
    L += ["", "## Abhidhamma dyads and suttantika dyads with «dhammā» (attributive form)", ""] + \
         [f"{p} = {F.TERMS[p]}" for p in keys[cut:]]
    L += ["", "## Cluster nouns (N)", ""] + [f"{st} = {d['N']}" for st, d in F.FAMILY.items()]
    L += ["", "## «ceva» terms", ""] + [f"{x} ceva … {y} ca = {m}" for (x, y), m in F.CEVA.items()] + \
         [f"{y} ceva … no / na ca {x} = {m}" for (y, x), m in F.CEVANO.items()]
    L += ["", "## Suttantika items", ""] + [f"{p} (ca) = {m}" for p, m in F.SUT.items()] + \
         [f"{p} = {m}" for p, m in F.MFIXED.items()]
    L += ["", "## Headings and colophons (group names)", ""] + [f"{p} = {m}" for p, m in F.COLO.items()]
    L += ["", "## Variant readings", "", f"different word = [{F.PATHA} (Sigla): …]; spelling only = "
          f"[{F.LEKHANA} (Sigla): …]", ""] + [f"{p} = {m}" for p, m in F.VAR_KIND.items()]
    txt = unicodedata.normalize("NFC", "\n".join(L) + "\n")
    (HERE / "my-zeroshot-terms.md").write_text(txt, encoding="utf-8")
    print("wrote my-zeroshot-terms.md")


if __name__ == "__main__":
    names = [a for a in sys.argv[1:] if not a.startswith("--")] or NAMES_OUT
    OUT.mkdir(parents=True, exist_ok=True)
    for n in names:
        if n == "preamble.md":
            preamble()
        else:
            chapter(n)
    if "--terms" in sys.argv or not [a for a in sys.argv[1:] if not a.startswith("--")]:
        write_terms()
