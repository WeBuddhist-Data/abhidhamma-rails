def kaha(g):
    """vuccati, agreeing with the Hindi noun: m / f / mpl / fpl"""
    return {"m": "कहा जाता है", "f": "कही जाती है", "mpl": "कहे जाते हैं", "fpl": "कही जाती हैं"}[g]


def called(name, g):
    """– ayaṃ / idaṃ vuccati "X".  (the dash is added by the caller)"""
    return f"यह “{name}” {kaha(g)}।"


def called_plain(name, g):
    """ayaṃ vuccati X (no quotes in the Pāli)"""
    return f"यह {name} {kaha(g)}।"


def q(name, pl=False):
    """Tattha katamo / katamā / katamaṃ X?"""
    return f"यहाँ {name} क्या {'हैं' if pl else 'है'}?"


def kaun(name, g):
    """Tattha katame / katamā / katamāni <n> X?  (plural list question)"""
    return f"यहाँ {name} कौन-{'से' if g == 'm' else 'सी'} हैं?"


def ime(name):
    """ime / imā / imāni <n> X."""
    return f"ये {name} हैं।"


