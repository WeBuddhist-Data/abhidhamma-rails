def build(name, lines):
    pali = S._read(os.path.join(S.PALI_DIR, name)).splitlines()
    pl = [l for l in pali if l.strip()]
    assert len(pl) == len(lines), f"{name}: {len(pl)} Pāli lines vs {len(lines)} Hindi lines"
    errs = []
    dash = lambda s: s.count("–") + s.count("—")
    for i, (p, h) in enumerate(zip(pl, lines), 1):
        p0 = S.ID.sub("", p)
        if dash(p0) != dash(h):
            errs.append(f"line {i}: dash {dash(p0)} vs {dash(h)}")
        if p0.count("[") != h.count("["):
            errs.append(f"line {i}: '[' {p0.count('[')} vs {h.count('[')}")
        if (len(p0) - len(p0.lstrip("#"))) != (len(h) - len(h.lstrip("#"))):
            errs.append(f"line {i}: heading level")
        if p0.rstrip().endswith("?") != h.rstrip().endswith("?"):
            errs.append(f"line {i}: final '?'")
        bare = re.sub(r"\[[^\]]*\]", "", h)
        if LATIN.search(bare):
            errs.append(f"line {i}: Latin outside brackets: {LATIN.findall(bare)[:5]}")
        if "—" in h or ":-" in h or "  " in h:
            errs.append(f"line {i}: em dash / ':-' / double space")
    if errs:
        print(name, "ERRORS:\n  " + "\n  ".join(errs))
        sys.exit(1)
    out = S.assemble(pali, lines)
    with open(os.path.join(S.HI_DIR, name), "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print(f"written {name}: {len(lines)} lines")


