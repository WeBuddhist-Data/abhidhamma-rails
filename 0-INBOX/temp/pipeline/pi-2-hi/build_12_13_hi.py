def santa(g, n):
    """santā honti samitā vūpasantā atthaṅgatā abbhatthaṅgatā appitā byappitā sositā visositā byantīkatā"""
    ck = {("m", "sg"): "चुका", ("f", "sg"): "चुकी", ("m", "pl"): "चुके", ("f", "pl"): "चुकी"}[(g, n)]
    hota = {("m", "sg"): "होता है", ("f", "sg"): "होती है", ("m", "pl"): "होते हैं", ("f", "pl"): "होती हैं"}[(g, n)]
    w = ["शांत हो", "थम", "पूरी तरह शांत हो", "अस्त हो", "पूरी तरह अस्त हो", "नष्ट हो", "पूरी तरह नष्ट हो", "सूख", "पूरी तरह सूख"]
    return ", ".join(f"{x} {ck}" for x in w) + f" और पूरी तरह समाप्त हो {ck} {hota}"


