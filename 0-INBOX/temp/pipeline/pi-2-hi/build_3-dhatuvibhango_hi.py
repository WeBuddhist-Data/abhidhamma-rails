PANHA_FIX = {'"parāmāsā ceva parāmaṭṭhā cāti parāmaṭṭhā ceva no ca parāmāsā"':
             '"parāmāsā ceva parāmaṭṭhā cā"ti, parāmaṭṭhā ceva no ca parāmāsā',
             # "kenaci viññeyyā, kenaci na viññeyyā" speak of all eighteen again (pronoun वे, as chapters 1, 2, 4)
             "siyā lokuttarā; kenaci viññeyyā": "siyā lokuttarā; ⟦R⟧kenaci viññeyyā"}


def panha(pali_line):
    for a, b in PANHA_FIX.items():
        pali_line = pali_line.replace(a, b)
    return panha_line(pali_line, ("अठारह तत्व", "अठारह तत्वों", "pl"))


