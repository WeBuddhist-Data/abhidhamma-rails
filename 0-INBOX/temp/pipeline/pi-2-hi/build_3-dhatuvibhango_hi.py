def inner(x, any_=False):
    """(yaṃ vā panaññampi atthi) ajjhattaṃ paccattaṃ <x> ajjhattaṃ upādinnaṃ"""
    return f"{'या जो कुछ भी अन्य' if any_ else 'जो कुछ'} स्वयं में, अपने भीतर {x} है, स्वयं में है और कर्म से उत्पन्न है"


def outer(x, any_=False):
    """(yaṃ vā panaññampi atthi) bāhiraṃ <x> bahiddhā anupādinnaṃ"""
    return f"{'या जो कुछ भी अन्य' if any_ else 'जो कुछ'} बाह्य {x} है, बाहर है और कर्म से उत्पन्न नहीं है"


def int_line(e, x_first, examples, x_rest=None):
    x_rest = x_rest or x_first
    return (f"यहाँ {E[e]} क्या है? {E[e]} दो प्रकार का है {DASH} कुछ आंतरिक है, कुछ बाह्य है। "
            f"यहाँ आंतरिक {E[e]} क्या है? {inner(x_first)}, जैसे {DASH} {examples}, {inner(x_rest, True)} "
            f"{called('आंतरिक ' + E[e])}")


def both(e):
    return f"जो आंतरिक {E[e]} है और जो बाह्य {E[e]} है, {TOGETHER} {called(E[e])}"


def ext_line(e, x, examples):
    head = f"यहाँ बाह्य {E[e]} क्या है? {outer(x)}"
    if examples:
        head += f", जैसे {DASH} {examples}, {outer(x, True)}"
    return f"{head} {called('बाह्य ' + E[e])} {both(e)}"


