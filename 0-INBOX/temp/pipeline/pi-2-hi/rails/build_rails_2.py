def pp(p):
    return PP.line(p, SUBJ, SPECIAL, SEMI)


def build(pali_lines):
    segs = S.segs_of_lines(pali_lines)
    src = {i: [S.ID.sub("", x).rstrip() for x in ls] for i, ls in segs}
    h = {}
    h["2-2-0"] = [f"### {TITLE}"]
    h["2-2-1-0"] = [f"#### {S.SUTTANTA_BH}"]
    h["2-154"] = [TWELVE_S, IMPERM_LINE, f"{S.SUTTANTA_BH}।"]
    h["2-2-2-0"] = [f"#### {S.ABHI_BH}"]
    h["2-155"] = [TWELVE_A]
    h["2-156"], h["2-157"], h["2-158"], h["2-159"], h["2-160"] = [EYE], [EAR], [NOSE], [TONGUE], [BODY]
    h["2-161"] = MANA_LINES
    h["2-162"], h["2-163"], h["2-164"], h["2-165"], h["2-166"] = [RUPA], [SADDA], [GANDHA], [RASA], [PHOTTHABBA]
    h["2-167"] = DHAMMA_LINES
    h["2-2-3-0"] = [f"#### {S.PANHA}"]
    h["2-168"] = [TWELVE_S]
    h["2-169"] = [QUESTION]
    h["2-2-3-1-0"] = ["##### तीन-तीन के वर्गीकरण"]
    h["2-170"] = [pp(x) for x in src["2-170"]]
    h["2-2-3-2-0"] = ["##### दो-दो के वर्गीकरण"]
    body = src["2-171"]
    assert body[-2:] == ["Pañhāpucchakaṃ.", "Āyatanavibhaṅgo niṭṭhito."], body[-2:]
    h["2-171"] = [pp(x) for x in body[:-2]] + [f"{S.PANHA}।", f"{TITLE} {S.DONE}।"]
    return h


def main():
    pali = (S.PALI / CH).read_text(encoding="utf-8").splitlines()
    S.emit(pali, build(pali), S.OUT / CH)


if __name__ == "__main__":
    main()
