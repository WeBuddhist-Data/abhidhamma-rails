def chain(seq, vip=False, first="vit"):
    """vitakkavicārānaṃ vūpasamā…pe… dutiyaṃ jhānaṃ…pe… tatiyaṃ jhānaṃ…pe… … X jhānaṃ upasampajja viharati"""
