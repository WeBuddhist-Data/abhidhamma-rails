"""Recurring frames check for phase 2 (pi-5 Burmese keyword mapping).

The 150 most frequent keywords of the WHOLE book (all mapper-my/*.keywords.md), each looked up by the SHARED module
map5_rules.py alone (no chapter table, no CTX: what a phase-2 script gets before it adds its own tables), in every
segment where it occurs; the value is checked against that segment's Burmese (the module's presence verifier) over
all 32 chapter files. Writes frame-coverage.md.

usage: /opt/homebrew/Caskroom/miniconda/base/bin/python3 -I -X utf8 frame_coverage.py
"""
import sys
import pathlib
import collections

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import map5_rules as R  # noqa: E402

TOP = 150

# why the module alone does not reach 100% for a keyword (checked segment by segment with work/fails.py); each is
# a genuine context difference that a phase-2 chapter table or CTX settles, not a module error
NOTES = {
    "vata": "ch11 ^5-377 the exclamation «Ime vata bhonto sattā» (not «vata re»): the chapter's own word",
    "dhamma": "compound senses: dhammacakka (ch3), sadhamma- / paradhammakusala (ch10), …: the teaching «တရား» vs "
              "the phenomenon «သဘောတရား» by the compound (a by_first stem list in the chapter table)",
    "sakadāgāmi": "an elided «Sakadāgāmi…pe…» with no Burmese name at that spot (ch13) and the niyāma compound (ch20)",
    "anāgāmi": "as sakadāgāmi", "rāgo": "asātarāga (ch21): the chapter's own word for the compound",
    "rāga": "the Asātarāgakathā heading (ch21)",
    "paṭisaṃvedī": "sukhapaṭisaṃvedī / ekantasukhaṃ paṭisaṃvedī in sutta quotations (ch17, ch19): the text's verb, "
                   "not the agent form",
    "citta": "cittavaṇḍa (ch12), cittiddhipāda (ch31): compound senses",
    "uppajjati": "ch1 ^5-230 (CTX of map_ch1.py, «ပေါ်ပေါက်လာ»); ch3 «sammāsambuddhā uppajjanti» the text's "
                 "honorific verb",
    "paṇidhi": "the Theragāthā verse of ch11 (^5-378) has its own wording",
    "sukha": "the Sukhānuppadānakathā of ch24 (heading, uddāna): the chapter's own word",
    "sukhaṃ": "ch24 «paraṅkataṃ sukhaṃ dukkhaṃ»: the chapter's own construction",
    "saha": "«saha dassanuppādā» (ch3, ch10): «together with the arising of vision», another construction",
    "gati": "ch3 «yattha natthi gati bhikkhūnaṃ» (access), another sense",
    "antarikā": "jhānantarikā / phassantarikā (ch26): the compound's own word",
    "viharati": "ch26 «lokaṃ abhibhuyya viharati»: the text's wording",
    "para": "parosahassaṃ (ch12, «more than»), parappavādā (ch28): other senses",
    "dānaṃ": "«dānaṃ dadeyya» (ch21, ch25): cognate object, one Burmese verb (pi-4 P4) — decide in the table",
    "nirodho": "ekuppādo ekanirodho (ch22) and the ch24 compounds: the compound's own word",
    "bhāvito": "ch30 sutta «āsevito bhāvito bahulīkato»: the list's own words",
}


def main():
    book = collections.Counter()
    occ = collections.defaultdict(list)
    for ch in R.CHAPTERS:
        for sid, kws in R.keyword_rows(ch):
            for k in kws:
                book[k] += 1
                occ[k].append((ch, sid))
    top = book.most_common(TOP)
    M = R.Mapper()
    rows, full = [], 0
    for kw, n in top:
        vals = collections.Counter()
        fails = collections.defaultdict(list)
        ok = 0
        for ch, sid in occ[kw]:
            my, pa = R.burmese(ch).get(sid, ""), R.pali(ch).get(sid, "")
            try:
                v = M.lookup(ch, sid, kw, pa, my)
            except KeyError:
                fails[ch].append((sid, "no value"))
                vals["(no value)"] += 1
                continue
            vals[v] += 1
            good, rules = R.presence(v, my)
            if good:
                ok += 1
            else:
                fails[ch].append((sid, f"«{rules[0][0]}» of «{v}» not in the segment"))
        rate = ok / n
        full += rate == 1.0
        rows.append((kw, n, vals, rate, fails))
    out = ["# pi-5 Burmese keyword mapping: recurring frames check (phase 1, for phase 2)", "",
           "Generated by `frame_coverage.py`. The 150 most frequent keywords of the whole book (all 32 "
           "`*.keywords.md`, 23,802 keyword uses), each looked up by the shared module `map5_rules.py` ALONE (no "
           "chapter table, no CTX) in every segment where it occurs, the value checked with the module's presence "
           "verifier against that segment's Burmese (all 32 chapter files of "
           "`AI_translation/burmese/pi-5-burmese-plain-zeroshot_split_chapters`).", "",
           f"**{full} of {TOP} keywords reach 100% presence** with the module alone; of all "
           f"{sum(n for _, n, _, _, _ in rows)} uses of the 150 keywords, {sum(round(r * n) for _, n, _, r, _ in rows)} "
           f"pass. The {TOP - full} others fail only in segments where the keyword stands in another compound, sense or "
           "construction (the note after each row says which); a phase-2 chapter table or CTX settles them. The "
           "module was corrected where a failure was a module error (jahati, paṇidhi, uddānaṃ, antarikā, samodhānaṃ, "
           "vīta, bhāvito, arahattā, phalā, bojjha / aṅgā, gati, taṇhā: values of the pi-5 text and its harmonise "
           "pass added to STOCK; paṭisaṃvedī by Q8).", "",
           "Values: the module's value per use (several = a context function chose by segment, or the pi-1 … pi-4 "
           "value present in that segment); «(no value)» = neither the module tables nor the pi-1 … pi-4 mappings "
           "nor the pi-5 terms give a value that the segment's Burmese has (the phase-2 table must add one). "
           "Chapters are listed by their number.", "",
           "| # | keyword | uses | module value (uses) | presence | chapters where it fails (segments) and why |",
           "|---|---|---|---|---|---|"]
    for i, (kw, n, vals, rate, fails) in enumerate(rows, 1):
        vs = "; ".join(f"{v} ({c})" for v, c in vals.most_common(4)) + (" …" if len(vals) > 4 else "")
        fl = []
        for ch, lst in sorted(fails.items(), key=lambda x: int(x[0].split("-")[0]) if x[0][0].isdigit() else 0):
            why = collections.Counter(w if w == "no value" else "absent" for _, w in lst)
            ex = lst[0]
            fl.append(f"{ch.split('-')[0]} ({len(lst)}: {', '.join(f'{k} {c}' for k, c in why.items())}; e.g. "
                      f"^{ex[0]} {ex[1]})")
        note = (" — " + NOTES[kw]) if kw in NOTES and fl else ""
        out.append(f"| {i} | {kw} | {n} | {vs} | {rate:.1%} | {'; '.join(fl) if fl else '—'}{note} |")
    (HERE / "frame-coverage.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("full", full, "of", TOP)
    for kw, n, vals, rate, fails in rows:
        if rate < 1:
            print(f"{rate:5.0%} {n:4d} {kw} :: " + "; ".join(f"{v} ({c})" for v, c in vals.most_common(3)) + " :: " +
                  " ".join(f"{ch.split('-')[0]}:{len(l)}" for ch, l in fails.items()))


if __name__ == "__main__":
    main()
