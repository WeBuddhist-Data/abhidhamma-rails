"""Write my5-zeroshot-terms.md (every formula and term of the pi-5 sample as «Pāli = Burmese») from the tables.

usage: python3 -I -X utf8 terms_my5.py
Reads my5_formulas.py and make_sample.py (nothing else); the formula templates are rendered by the real frame
functions with the placeholder propositions P / Q (so the file always shows what the generator does).
"""
import pathlib
import sys

sys.dont_write_bytecode = True
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import make_sample as MS  # noqa: E402
F = MS.F

# placeholder propositions for the templates: a positive clause «P» / «Q» (verb «ဖြစ်»)
F.PROP["p_"] = F.V("P")
F.PROP["q_"] = F.V("Q")
out = []
w = out.append


def sec(t):
    w(f"\n## {t}\n")


def row(p, m):
    w(f"- {p} = {m}")


w("# pi-5 Burmese zero-shot: formulas and terms (sample: preamble, 1-puggalakatha)\n")
w("Generated by terms_my5.py from my5_formulas.py and make_sample.py; do not edit by hand. «P», «Q» stand for "
  "any proposition (rendered by the clause forms below). Status: proposed with the sample, for review.")

sec("1. Book title and frame")
row("Kathāvatthupāḷi (book title, Burmese only)", F.TITLE)
row("Kathāvatthupakaraṇaṃ niṭṭhitaṃ (book end, pattern of pi-1 … pi-3)", F.BOOK_END + F.END)
row("Namo tassa bhagavato arahato sammāsambuddhassa (pi-1 final)", F.NAMO)
row("Abhidhammapiṭake (pi-1 final)", F.ABHI)
row("Kathāvatthu in a reference (“…”)", f"“{F.TITLE}”")

sec("2. Kathā, anuyoga and vagga headings and colophons")
row("Xkathā (heading) = X + kathā", f"X အကြောင်း {F.KATHA_W} (e.g. Puggalakathā = {F.SECTION['Puggalakathā']})")
row("Xkathā niṭṭhitā. (section end, pi-1 pattern «“…” ပြီးဆုံးပြီ»)", F.DONE.format("X") + F.END)
row("Xanuyogo (an inquiry)", f"Xကို {F.ANUYOGA_W}")
row("vagga", F.VAGGA_W)
row("Kalyāṇavaggo paṭhamo. (vagga colophon: ordinal + name + vagga)", F.vagga_end("Kalyāṇa", 1) + F.END)
for k, v in F.SECTION.items():
    row(k, v)
for k in ("Suddhasaccikaṭṭho", "Anulomapaccanīkaṃ", "Paccanīkānulomaṃ", "(Ka) okāsasaccikaṭṭho",
          "(Ka) kālasaccikaṭṭho", "(Ka) avayavasaccikaṭṭho", "(Kha) okāsasaccikaṭṭho"):
    row(k, F.HEAD[k])
row("(Ka) / (Kha) item letters", "(က) / (ခ)")

sec("3. The dialectic formulas (frames)")
row("P-ti? (question)", F.prop_my("p_", "q") + F.END)
row("Āmantā.", F.YES + F.END)
row("Na hevaṃ vattabbe.", F.NO_SAY + F.END)
row("Na hevaṃ vattabbe…pe…", F.NO_SAY + F.PE)
row("Vattabbaṃ. (answer)", F.SAY_ANS + F.END)
row("Ājānāhi niggahaṃ.", F.AJ["niggahaṃ"] + F.END)
row("Ājānāhi paṭikammaṃ.", F.AJ["paṭikammaṃ"] + F.END)
row("Hañci P, tena vata re vattabbe – \"Q\"ti.", F.if_my("p_", "q_") + F.END)
row("Hañci vā pana P, tena vata re vattabbe – \"Q\"ti.", F.if_my("p_", "q_", alt=True) + F.END)
row("Hañci P; no ca vata re vattabbe – \"Q\"ti.", F.if_my("p_", "q_", neg=True) + F.END)
row("Yaṃ tattha vadesi – \"vattabbe kho – ‘P,’ no ca vattabbe – ‘Q’\"ti micchā.", F.yam_my("p_", "q_") + F.END)
row("Yaṃ tattha vadesi – \"…\"ti idaṃ te micchā.", F.yam_my("p_", "q_", te=True) + F.END)
row("Yaṃ tattha vadesi – \"vattabbe kho – ‘P’\"ti micchā. (claim without «no ca», ^5-116)",
    F.yam_my("p_", None) + F.END)
row("No ce pana vattabbe – \"Q\"ti, no ca vata re vattabbe – \"P\"ti.", F.ifnot_my("q_", "p_") + F.END)
row("Tvaṃ ce pana maññasi – \"vattabbe kho – ‘P’, no ca vattabbe – ‘Q’\"ti, tena tava tattha hetāya paṭiññāya "
    "hevaṃ paṭijānantaṃ hevaṃ niggahetabbe. Atha taṃ niggaṇhāma. Suniggahito ca hosi.",
    f"တစ်ဖန် အကယ်၍ သင်သည် ဤသို့ ထင်လျှင် – “{F.claim('p_', 'q_', 1)}”{F.C} {F.TVAM_TAIL}")
row("Ese ce dunniggahite hevamevaṃ tattha dakkha. Vattabbe kho – \"P,\" no ca vattabbe – \"Q\"ti. No ca mayaṃ "
    "tayā tattha hetāya paṭiññāya hevaṃ paṭijānantā hevaṃ niggahetabbā. Atha maṃ niggaṇhāsi. Dunniggahitā ca homa.",
    f"{F.ESE_HEAD} {F.claim('p_', 'q_', 0)}{F.END} {F.ESE_TAIL}")
row("Na hevaṃ niggahetabbe. Tena hi yaṃ niggaṇhāsi – \"hañci P, tena vata re vattabbe – ‘Q’ti. Yaṃ tattha vadesi "
    "– ‘vattabbe kho – P, no ca vattabbe – Q’\"ti micchā.",
    f"{F.NA_HEAD} သို့ဖြစ်၍ သင် ချေပသည်မှာ – “{F.if_my('p_', 'q_', depth=1)}{F.END} {F.yam_my('p_', 'q_', depth=1)}”"
    f"{F.END}")
for k, v in F.TAIL.items():
    row(k, v)
row("Na vattabbaṃ – \"P\"ti?", f"ဤသို့ မဆိုသင့်သလော – “{F.prop_my('p_', 'stmt', 1)}”{F.END}")
row("Nanu P-ti?", F.prop_my("p_", "nanu") + F.END)
row("Nanu vuttaṃ bhagavatā – \"X\"ti? / !", F.vutt_cl("X").f("nanu") + F.END)
row("Vuttaṃ bhagavatā – \"X\"ti. / ?", F.vutt_cl("X").f("stmt") + F.END + " / " + F.vutt_cl("X").f("q") + F.END)
row("Nanu vuttaṃ bhagavatā – (verse on the next lines)", F.SENT["Nanu vuttaṃ bhagavatā –"])
row("Attheva suttantoti?", F.ATTHEVA + F.END)
row("Tena hi P-ti.", f"{F.TENA_HI} {F.prop_my('p_', 'stmt')}{F.END}")
row("Tena hi na vattabbaṃ – \"P\"ti.", f"{F.TENA_HI} ဤသို့ မဆိုသင့် – “{F.prop_my('p_', 'stmt', 1)}”{F.END}")
row("X-ti katvā tena ca kāraṇena P-ti?", f"X{F.KATVA} {F.TENA_CA} {F.prop_my('p_', 'q')}{F.END}")
row("X-ti katvā teneva kāraṇena P-ti?", f"X{F.KATVA} {F.TENEVA} {F.prop_my('p_', 'q')}{F.END}")
row("X-ti katvā? (^5-88)", "Xဟု အကြောင်းပြုသလော" + F.END)
row("X; tena hi P-ti. (^5-214)", f"X{F.C} {F.TENA_HI} {F.prop_my('p_', 'stmt')}{F.END}")
row("P-ti micchā. (^5-78)", f"{F.prop_my('p_', 'stmt')} ဟူသည် မှားသည်{F.END}")
row("…pe… / …Pe… / … (inside or at the end of a line)", "… (one ellipsis; a line ending «…pe….» ends «…», "
    "no full stop)")
row("Na hevaṃ vattabbe.…Pe…. (^5-238)", F.NO_SAY + F.END + " " + F.PE)
row("(Saṃkhittaṃ)", F.SANKHITTA)
row("( ) (an empty bracket of the edition, kept)", "( )")

sec("4. Clause forms (one proposition, five renderings)")
_ex = F.found_cl(F.PUG)
for form, what in (("stmt", "statement / inside a quotation"), ("q", "question …ti?"), ("cond", "condition Hañci …"),
                   ("bare", "elided series item / a line ending «…pe….»"), ("nanu", "Nanu …ti?")):
    row(f"puggalo upalabbhati saccikaṭṭhaparamatthena, {what}", _ex.f(form))
_ex = F.found_cl(F.PUG, neg=True)
row("puggalo nupalabbhati saccikaṭṭhaparamatthena (statement / question)", _ex.f("stmt") + " / " + _ex.f("q"))
w("- A compound proposition «A, B» = «A(statement)၊ B(form)»; a part ending in «ti» inside a compound = "
  "«…ဟူ၍၊»; series items «A…pe… B…pe… C» take the form of the whole (bare forms when a «, » part follows).")
w("- Quotation marks are set by depth: “…” inside the sentence, ‘…’ inside “…”, none inside ‘…’ (as the Pāli).")

sec("5. Set names (closers) and refutation ordinals")
for k, v in F.CLOSE.items():
    row(k + ".", v + F.END)
for k, n in (("Paṭhamo", 1), ("Dutiyo", 2), ("Tatiyo", 3), ("Catuttho", 4), ("Pañcamo", 5), ("Chaṭṭho", 6),
             ("Sattamo", 7)):
    row(f"{k} niggaho.", F.niggaho_my(n) + F.END)
row("niggaha / paṭikamma", f"{F.NIGGAHA} / {F.PATIKAMMA}")

sec("6. Speakers, editorial notes, variants and references")
row("sakavādī / paravādī", f"{F.SAKAVADI} / {F.PARAVADI}")
for k, v in F.NOTE.items():
    row(f"[{k}]", f"[{v}]")
row("[reading (sigla)] word / spelling variant", f"[{F.PATHA} (Syā.): …] / [{F.LEKHANA} (Syā.): …]")
row("sigla (bahūsu) / (?)", f"({F.SIGLA['bahūsu']}) / ({F.SIGLA['?']})")
for k, v in F.REF.items():
    row(k, v)
for k, v in F.REF_NOTE.items():
    row(k, v)
for k, v in F.BR_TABLE.items():
    row(k, v)

sec("7. Core terms of the Puggalakathā")
for p, m in (("saccikaṭṭhaparamatthena", F.SACC), ("saccikaṭṭho paramattho", F.FACT),
             ("yo saccikaṭṭho paramattho, tato (so puggalo …)", f"{F.FACT_AS} (ထိုပုဂ္ဂိုလ်ကို …)"),
             ("saccikaṭṭho (alone)", F.SACCIKATTHA_W), ("upalabbhati / nupalabbhati", f"{F.FOUND} / မ{F.FOUND}"),
             ("puggala", F.PUGGALA), ("sabbattha / sabbadā / sabbesu", " / ".join(F.WHERE.values())),
             ("aññaṃ A añño B", f"Aနှင့် Bသည် {F.OTHER} ဖြစ်"), ("upādāya", F.UPADAYA), ("paññatti", F.PANNATTI),
             ("koci", MS.KOCI), ("sandhāvati", MS.SANDH), ("cavati / cuto / cavamāne", f"{MS.CAVATI} / သေ၍ / သေဆဲ"),
             ("upapajjati", MS.UPAP), ("paññāyati", MS.PAN), ("kattā kāretā", MS.KATTA), ("paṭisaṃvedī", MS.PSV),
             ("vipākapaṭisaṃvedī", MS.VPSV), ("kārako", MS.KARAKA), ("sukhadukkha", MS.SD),
             ("abyākata", MS.ABY), ("yathākammūpaga", MS.YK), ("anicca … vipariṇāmadhamma (list)", MS.ANICCA),
             ("nicca dhuva sassata avipariṇāmadhamma", MS.NICCA), ("bhagavā saccavādī … anaññathavādī",
                                                                  MS.SACCAVADI)):
    row(p, m)

sec("8. Persons and things (new or reused names)")
for k, v in MS.PN.items():
    row(k, v)
for k, (v, g) in MS.THING.items():
    row(k, v)
for k, v in MS.REL.items():
    row(f"(yo / atthi koci) {k}", v)
for k, v in MS.HAVER.items():
    row(f"{k} puggalo", f"{v} {F.PUGGALA}")
for k, v in MS.PATH.items():
    row(k, v)
for k, v in MS.LAK.items():
    row(f"puggalo {k}", f"{F.PUGGALA}သည် {v} အရာ")
for p, m in MS._MAIM:
    row(p, m)

sec("9. The propositions of the Puggalakathā (statement form)")
for k, v in F.PROP.items():
    if k in ("p_", "q_"):
        continue
    row(k, v.f("stmt"))

sec("10. Sutta quotations and unique sentences / lines")
for k, v in F.QUOTE.items():
    row(k, F.q_set(v, 0))
for k, v in F.SENT.items():
    row(k, v)
for k, v in F.LINES.items():
    row(k, v)

sec("11. Reused from pi-1 … pi-4 (FINAL rails texts, witnessed: Pāli in the segment, Burmese in its rails text)")
for k, (b, bid, my) in F.WITNESS.items():
    row(f"{k} (pi-{b} {bid})", my)

(HERE / "my5-zeroshot-terms.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"wrote my5-zeroshot-terms.md ({len(out)} lines)")
