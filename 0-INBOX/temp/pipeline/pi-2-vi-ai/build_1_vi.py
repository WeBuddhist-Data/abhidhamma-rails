def atthi_pred(surface):
    if surface in ATTHI_N:
        return ATTHI_N[surface]
    UNUSED.discard(surface)
    return P(SURF[surface])


def chunk_abhi(c):
    """One phrase between separators of an Abhidhammabhājanīya line -> (Vietnamese, has «có loại»)."""
    m = CLOSE.match(c)
    if m:
        vi = frame_close(AGG_PALI[m.group(3)], NUMKEY[m.group(2).lower()])
        return (vi if m.group(1) == "E" else low(vi)), False
    if low(c) in SUBJ:
        vi, atthi = SUBJ[low(c)], False
    elif c in BARE:
        vi, atthi = BARE[c], False
    else:
        m = re.match(r"^()[Aa]tthi (.+)$", c) or re.match(r"^(.*?) atthi (.+)$", c)
        if not m:
            raise KeyError("abhi chunk: " + c)
        subj, pred = m.group(1), m.group(2)
        preds = pred.split(" atthi ")
        if len(preds) > 1:
            SLIPS.append("missing comma: " + c)
        body = ", ".join(f"{ATTHI} {atthi_pred(x)}" for x in preds)
        vi = f"{SUBJ[subj]}: {body}" if subj else body   # pi-1 RUPA_ATTHA / RUPA_DASA: «X: có loại …»
        atthi = True
    return (cap(vi) if c[:1].isupper() else vi), atthi


def sep_vi(x):
    if x.startswith(PE):   # "…pe…" -> "…"; "…pe…." -> "…" (never «….», pi-1 ^1-152)
        return "…" + (" " if x.endswith(" ") else "")
    return x


def body_abhi(body):
    body = body.replace(" …pe…", "…pe…").replace("…pe…", PE)
    parts = re.split(r"(\x01\.? ?|, |; |\. |\.$)", body)
    out, prev_atthi = [], False
    for i, x in enumerate(parts):
        if i % 2:
            out.append(sep_vi(x))
        elif x:
            vi, atthi = chunk_abhi(x)
            # after a «X: có loại …» list, a following item is set off by ";" (sample RUPA_ATTHA)
            if out and out[-1] == ", " and prev_atthi and not atthi:
                out[-1] = "; "
            out.append(vi)
            prev_atthi = atthi
    return "".join(out)


def line_abhi(t):
    if t in LABELS:
        return LABELS[t]
    pre = ""
    m = re.match(r"^Tattha katamo (\w+?)kkhandho\? ", t)
    if m:
        pre = S.khandha_question(AGG_PALI[m.group(1)]) + " "
        t = t[m.end():]
    m = FRAME.match(t)
    if not m:   # a list continued on the next line ("Atthi gantho, atthi no gantho. …")
        if not pre and t.startswith("Atthi "):
            return body_abhi(t)
        raise KeyError("abhi line: " + t[:80])
    vi = frame_open(AGG_PALI[m.group(3)], NUMKEY[m.group(2).lower()], other=bool(m.group(1)))
    rest = t[m.end():]
    if rest.startswith(" " + DASH + " "):
        vi += " " + DASH + " " + body_abhi(rest[3:])
    elif rest.startswith("…pe…"):
        vi += body_abhi(rest)
    elif rest.startswith(" "):   # dash missing in the Pāli (reported): a colon, no dash
        SLIPS.append("missing dash: " + t[:60])
        vi += ": " + body_abhi(rest[1:])
    else:
        raise KeyError("abhi frame rest: " + rest[:40])
    return pre + vi


# ---------------------------------------------------------------- 4. Pañhāpucchaka
SUBJECTS = {f"{cap(pa)}kkhandho": cap(S.AGG[a]["khandha"]) for pa, a in AGG_PALI.items()}
SUBJECTS.update({"Cattāro khandhā": "Bốn khối", "cattāro khandhā": "bốn khối",
                 "Tayo khandhā": "Ba khối", "Dve khandhā": "Hai khối"})
SUBJ_RE = re.compile(r"^(" + "|".join(map(re.escape, SUBJECTS)) + r") (.+)$")
NV = "không nên nói " + DASH + " rằng"      # na vattabbo – "…"ti  [pi-1 ^1-1198 «không nên nói – rằng …»]
OR = "hay rằng"                              # "…"tipi (second and later)  [pi-1]
SOMETIMES = "đôi khi"                        # siyā  [pi-1 ^1-1404, ^1-1422]
QUOTE_RE = re.compile(r'^"([^"]*)"(n?)ti(pi)?$')


def pred(surface):
    UNUSED.discard(surface)
    return ITEMS[SURF[surface]]["s"]


def quoted(q, n):
    q = q + ("ṃ" if n else "")
    q = re.sub(r" cā$", " ca", q)
    UNUSED.discard(q)
    return "“" + P(SURF[q]) + "”"


def chunk_q(c, state):
    subj = ""
    m = SUBJ_RE.match(c)
    if m:
        subj, c = SUBJECTS[m.group(1)], m.group(2)
    m = re.match(r"^(siyā )?na vattabb[oā] " + DASH + r" (.+)$", c)
    if m:
        qm = QUOTE_RE.match(m.group(2))
        vi = f"{NV} {quoted(qm.group(1), qm.group(2))}"
        if m.group(1):
            vi = f"{SOMETIMES} {vi}"
        elif subj:
            vi = f"{S.THI} {vi}"   # «Khối vật chất thì không nên nói – rằng …» (topic, like the sample's «thì»)
        state["nv"] = True
    elif QUOTE_RE.match(c):
        qm = QUOTE_RE.match(c)
        vi = f"{OR} {quoted(qm.group(1), qm.group(2))}"
        state["nv"] = True
    else:
        if re.match(r'^"[^"]*"$', c):   # quoted without "ti": an affirmative, as in the āsava line (reported)
            SLIPS.append("quoted affirmative without ti: " + c)
            c = c[1:-1]
        if c.startswith("siyā "):
            vi = f"{SOMETIMES} {pred(c[5:])}"
        else:
            vi = pred(c)
            if state.get("nv"):   # the affirmative after a «không nên nói» clause: «mà là …»
                vi = "mà " + vi
        state["nv"] = False
    return f"{subj} {vi}" if subj else vi


def line_q(t):
    if t in LABELS:
        return LABELS[t]
    # punctuation slips in the Pāli (reported): missing opening quote; "ti pi"; the closing "ti" of the question
    fixes = ((DASH + ' kilesasampayuttā ceva no ca kilesā"ti', DASH + ' "kilesasampayuttā ceva no ca kilesā"ti'),
             ('"ti pi', '"tipi'), ("siyā araṇāti.", "siyā araṇā."))
    for a, b in fixes:
        if a in t:
            SLIPS.append("punctuation: " + a)
            t = t.replace(a, b)
    sents = re.split(r"(?<=\.) (?=[A-ZĀ])", t)
    out = []
    for sent in sents:
        assert sent.endswith("."), sent[-40:]
        body = sent[:-1].replace("…pe…", PE)
        parts = re.split(r"(, |; |\x01 ?)", body)
        state = {}
        vi = []
        for i, x in enumerate(parts):
            if i % 2:
                vi.append(sep_vi(x))
                if x.startswith(PE) or x == "; ":
                    state["nv"] = False
            else:
                vi.append(chunk_q(x, state))
        out.append(cap("".join(vi)) + ".")
    return " ".join(out)


