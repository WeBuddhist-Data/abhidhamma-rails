def translate_rest(lines):
    out, section = [], "abhi"
    for pl in lines:
        if not pl.strip():
            out.append("")
            continue
        m = S.ID.search(pl)
        t = S.ID.sub("", pl).rstrip()
        if t.startswith("#### Pañhāpucchakaṃ"):
            section = "q"
        vi = line_abhi(t) if section == "abhi" else line_q(t)
        assert pl.count(DASH) + pl.count("—") == vi.count(DASH) and "—" not in vi, ("dash count", t[:70], vi[:70])
        assert "là là" not in vi and "  " not in vi and "…." not in vi and '"' not in vi, vi[:120]
        out.append(vi + (" " + m.group(1) if m else ""))
    return out


def build():
    pali = open(PALI_FILE, encoding="utf-8").read().rstrip("\n").split("\n")
    idx = pali.index(START)
    assert pali[idx - 1] == ""
    head_nonempty = [l for l in pali[:idx] if l.strip()]
    sample = open(SAMPLE_FILE, encoding="utf-8", newline="").read()
    assert sample.endswith("\n") and "\r" not in sample
    assert len(head_nonempty) == 77 == len([l for l in sample.split("\n") if l.strip()])
    rest = translate_rest(pali[idx:])
    return sample, sample + "\n" + "\n".join(rest).rstrip("\n") + "\n"


