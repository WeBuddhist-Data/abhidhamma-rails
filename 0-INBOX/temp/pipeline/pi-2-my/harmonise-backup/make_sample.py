"""Burmese zero-shot sample of pi-2 (Vibhaṅga, «ခွဲခြမ်းစိတ်ဖြာခြင်း»): preamble and 1-khandhavibhango.

usage: python3 -I -X utf8 make_sample.py [chapter ...] [--terms]
Every line is generated from the Pāli by my2_formulas.translate_line() through the frames and tables of
my2_formulas.py (which loads the FINAL pi-1 Burmese module read-only); a sentence no frame or table entry matches stops
the run (my2_formulas.Miss), nothing is guessed. A chapter is written only when every line passed; on a stop the
lines that passed go to scratch/partial-<chapter> and the failing line is printed. --terms (also by default with no
chapter argument) rewrites my2-zeroshot-terms.md from the tables.
Model for later chapters: copy this file, add your entries to the tables (or a tables module), frames to
F.EXTRA_RULES, then F.rebuild(); change NAMES_OUT.
"""
import pathlib
import sys
import unicodedata

sys.dont_write_bytecode = True
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import my2_formulas as F  # noqa: E402

ROOT = HERE.parents[3]
PALI = ROOT / "AI_translation/pali/pi-2_split_chapters"
OUT = ROOT / "AI_translation/burmese/pi-2-burmese-plain-zeroshot_split_chapters"
NAMES_OUT = ["preamble.md", "1-khandhavibhango.md"]


def write(name, txt):
    txt = unicodedata.normalize("NFC", txt)
    (OUT / name).write_text(txt, encoding="utf-8")
    print(f"wrote {name}: {sum(1 for l in txt.splitlines() if l)} lines")


def preamble():
    name = "preamble.md"
    rep = {"Namo tassa bhagavato arahato sammāsambuddhassa": F.NAMO, "# Abhidhammapiṭake": "# " + F.ABHI,
           "## Vibhaṅgapāḷi": "## " + F.TITLE}
    out = []
    for line in (PALI / name).read_text(encoding="utf-8-sig").splitlines():
        m = F.ID_RE.search(line)
        t = line[:m.start()] if m else line
        if t.strip():
            if t not in rep:
                raise F.Miss("preamble: " + t)
            t = rep[t]
        out.append(t + (" " + m.group(1) if m else ""))
    write(name, "\n".join(out) + "\n")


def chapter(name):
    lines = (PALI / name).read_text(encoding="utf-8-sig").splitlines()
    done = []
    F.STATE.clear()
    for i, line in enumerate(lines):
        try:
            done.append(F.translate_line(line))
        except F.Miss as e:
            part = HERE / "scratch" / ("partial-" + name)
            part.parent.mkdir(exist_ok=True)
            part.write_text("\n".join(done) + "\n", encoding="utf-8")
            print(f"STOP {name} line {i + 1}: {e}\n  {line[:160]}\n  ({len(done)} lines kept in {part})")
            sys.exit(1)
    write(name, "\n".join(done).rstrip("\n") + "\n")


