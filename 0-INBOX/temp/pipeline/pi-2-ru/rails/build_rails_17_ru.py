def numbered(items, extra=None):
    """(1) X (2) y … , the first item capitalised; extra = {n: suffix (variant bracket)}"""
    out = []
    for n, it in enumerate(items, 1):
        t = cap(it) if n == 1 else it
        out.append(f"({n}) {t}{(extra or {}).get(n, '')}")
    return " ".join(out)


