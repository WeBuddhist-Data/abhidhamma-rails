ID = re.compile(r"\^([0-9A-Za-z-]+)\s*$")


def pali_segments(text):
    segs, cur = [], []
    for ln in text.splitlines():
        if not ln.strip():
            continue
        cur.append(ln)
        m = ID.search(ln)
        if m:
            segs.append((m.group(1), cur))
            cur = []
    assert not cur, "trailing lines without an ID"
    return segs


