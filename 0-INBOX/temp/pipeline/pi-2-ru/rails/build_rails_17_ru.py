    sep = "," if "вызывающ" in adj(_OBJ[0]) else ""                      # close the participial phrase before the body
    return f"В отношении {adj(_OBJ[0])}{sep} {body}, {mid}… в отношении {adj(_OBJ[5])}{sep} {body}{close}"


