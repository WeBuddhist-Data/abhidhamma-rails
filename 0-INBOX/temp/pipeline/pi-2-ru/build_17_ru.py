def heading(p):
    if p in HEAD:
        return HEAD[p]
    m = re.match(r"^(#+) \((\d+)\) (.+)$", p)
    sec = STATE["sec"]
    if m:
        hashes, n = m.group(1), int(m.group(2))
        if sec == "ekaka":
            return f"{hashes} ({n}) {cap(EK[n - 1][0])}"
        lists = {"duka": DU, "tika": TI, "catukka": CA, "pañcaka": PA, "chakka": CH, "sattaka": SA, "aṭṭhaka": AT,
                 "navaka": NA, "dasaka": DA}
        if sec == "catukka" and n == 1:
            return f"{hashes} ({n}) {cap(CA[0])}"
        return f"{hashes} ({n}) {cap(lists[sec][n - 1])}"
    m = re.match(r"^(#+) \((\d+)\. (Ka)\) (.+)$", p)
    if m:
        STATE["sub"] = int(m.group(2))
        subs = TIKA_SUB[int(m.group(2))]
        return f"{m.group(1)} ({m.group(2)}. а) {subs[0]}"
    m = re.match(r"^(#+) \((Kha|Ga|Gha)\) (.+)$", p)
    if m:
        idx = {"Kha": 1, "Ga": 2, "Gha": 3}[m.group(2)]
        if sec == "tika":
            return f"{m.group(1)} ({LAB[m.group(2)]}) {TIKA_SUB[STATE['sub']][idx]}"
        return f"{m.group(1)} ({LAB[m.group(2)]}) {CATU_SUB[STATE['csub']][idx]}"
    m = re.match(r"^(#+) \((Ka)\) (.+)$", p)
    if m:
        return f"{m.group(1)} (а) {CATU_SUB[STATE['csub']][0]}"
    raise KeyError(p)


