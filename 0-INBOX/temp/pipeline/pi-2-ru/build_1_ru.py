def atthi_pred(surface):
    if surface in ATTHI_N:
        return ATTHI_N[surface]
    key = SURF[surface]
    UNUSED.discard(surface)
    b = ITEMS[key]["b"]
    if b is None:
        raise KeyError("no «бывает» form: " + surface)
    return b


def chunk_abhi(c):
    """One phrase between separators of an Abhidhammabhājanīya line."""
    m = CLOSE.match(c)
    if m:
        a = AGG_PALI[m.group(3)]
        ru = frame_close(a, NUM[m.group(2).lower()])
        return ru if m.group(1) == "E" else low(ru)
    if low(c) in SUBJ:
        ru = SUBJ[low(c)][0]
    elif c in BARE:
        ru = BARE[c]
    else:
        m = re.match(r"^()[Aa]tthi (.+)$", c) or re.match(r"^(.*?) atthi (.+)$", c)
        if not m:
            raise KeyError("abhi chunk: " + c)
        subj, pred = m.group(1), m.group(2)
        preds = [atthi_pred(x) for x in pred.split(" atthi ")]   # a missing comma in the Pāli (reported)
        body = ", бывает ".join(preds)
        if subj:
            s_ru, close = SUBJ[subj]
            ru = s_ru + ("," if close else "") + " бывает " + body
        else:
            ru = "бывает " + body
    return cap(ru) if is_upper(c) else ru


def body_abhi(body):
    body = body.replace(" …pe…", "…pe…").replace("…pe…", PE)
    parts = re.split(r"(\x01\.? ?|, |; |\. |\.$)", body)
    out = []
    for i, x in enumerate(parts):
        if i % 2:
            out.append(x.replace(PE, "…"))
        elif x:
            out.append(chunk_abhi(x))
    return "".join(out)


def line_abhi(t):
    if t in LABELS:
        return LABELS[t]
    pre = ""
    m = re.match(r"^Tattha katamo (\w+?)kkhandho\? ", t)
    if m:
        pre = S.khandha_question(AGG_PALI[m.group(1)]) + " "
        t = t[m.end():]
    m = FRAME.match(t)
    if not m:   # a list continued on the next line ("Atthi gantho, atthi no gantho. …")
        if not pre and t.startswith("Atthi "):
            return body_abhi(t)
        raise KeyError("abhi line: " + t[:80])
    a = AGG_PALI[m.group(3)]
    ru = frame_open(a, NUM[m.group(2).lower()], other=bool(m.group(1)))
    rest = t[m.end():]
    if rest.startswith(" " + DASH + " "):
        ru += " " + DASH + " " + body_abhi(rest[3:])
    elif rest.startswith("…pe…"):
        ru += body_abhi(rest)
    elif rest.startswith(" "):   # dash missing in the Pāli (reported): a colon, no dash
        ru += ": " + body_abhi(rest[1:])
    else:
        raise KeyError("abhi frame rest: " + rest[:40])
    return pre + ru


# ---------------------------------------------------------------- 4. Pañhāpucchaka
SUBJECTS = {"Rūpakkhandho": ("Совокупность материальной формы", "sg"),
            "Vedanākkhandho": ("Совокупность чувств", "sg"),
            "Saṅkhārakkhandho": ("Совокупность формирующих факторов", "sg"),
            "Viññāṇakkhandho": ("Совокупность сознания", "sg"),
            "Cattāro khandhā": ("Четыре совокупности", "pl"),
            "cattāro khandhā": ("четыре совокупности", "pl"),
            "Tayo khandhā": ("Три совокупности", "pl"),
            "Dve khandhā": ("Две совокупности", "pl")}
SUBJ_RE = re.compile(r"^(" + "|".join(map(re.escape, SUBJECTS)) + r") (.+)$")
NV = "нельзя определить"
PRON = {"sg": "её", "pl": "их"}
QUOTE_RE = re.compile(r'^"([^"]*)"(n?)ti(pi)?$')


def pred(surface, num):
    key = SURF[surface]
    UNUSED.discard(surface)
    r = ITEMS[key]["s" if num == "sg" else "p"]
    if r is None:
        raise KeyError(f"no {num} predicate: {surface}")
    return r


def quote(q, n, pi, num):
    q = q + ("ṃ" if n else "")
    q = re.sub(r" cā$", " ca", q)
    key = SURF[q]
    UNUSED.discard(q)
    f = ITEMS[key]["qs" if num == "sg" else "qp"]
    if f is None:
        raise KeyError(f"no {num} quote form: {q}")
    return ("ни как" if pi else "как") + " «" + f + "»"


def chunk_q(c, state):
    subj_ru = ""
    m = SUBJ_RE.match(c)
    if m:
        subj_ru, state["num"] = SUBJECTS[m.group(1)]
        c = m.group(2)
    num = state["num"]
    m = re.match(r"^(siyā )?na vattabb[oā] " + DASH + r" (.+)$", c)
    if m:
        qm = QUOTE_RE.match(m.group(2))
        q = quote(qm.group(1), qm.group(2), qm.group(3), num)
        if m.group(1):
            ru = f"иногда {PRON[num]} {NV} {DASH} {q}"
        else:
            ru = f"{NV} {DASH} {q}"
    elif QUOTE_RE.match(c):
        qm = QUOTE_RE.match(c)
        ru = quote(qm.group(1), qm.group(2), qm.group(3), num)
    elif re.match(r'^"[^"]*"$', c):   # quoted, no "ti": an affirmative statement (as in the āsava cluster); reported
        ru = pred(c[1:-1], num)
    elif c.startswith("siyā "):
        ru = "иногда " + pred(c[5:], num)
    else:
        ru = pred(c, num)
    return (subj_ru + " " + ru) if subj_ru else ru


def line_q(t):
    if t in LABELS:
        return LABELS[t]
    # punctuation slips in the Pāli (reported): missing opening quote; "ti pi"; the closing "ti" of the question
    t = t.replace(DASH + ' kilesasampayuttā ceva no ca kilesā"ti', DASH + ' "kilesasampayuttā ceva no ca kilesā"ti')
    t = t.replace('"ti pi', '"tipi').replace("siyā araṇāti.", "siyā araṇā.")
    sents = re.split(r"(?<=\.) (?=[A-ZĀ])", t)
    out = []
    for sent in sents:
        assert sent.endswith("."), sent[-40:]
        body = sent[:-1].replace("…pe…", PE)
        parts = re.split(r"(, |; |\x01 ?)", body)
        state = {"num": None}
        ru = []
        for i, x in enumerate(parts):
            if i % 2:
                ru.append(x.replace(PE, "…"))
            else:
                ru.append(chunk_q(x, state))
        out.append(cap("".join(ru)) + ".")
    return " ".join(out)


# ---------------------------------------------------------------- 5. build
def translate_rest(lines):
    out, section = [], "abhi"
    for pl in lines:
        if not pl.strip():
            out.append("")
            continue
        m = S.ID.search(pl)
        t = S.ID.sub("", pl).rstrip()
        if t.startswith("#### Pañhāpucchakaṃ"):
            section = "q"
        ru = line_abhi(t) if section == "abhi" else line_q(t)
        assert pl.count(DASH) + pl.count("—") == ru.count(DASH), ("dash count", t[:70], ru[:70])
        out.append(ru + (" " + m.group(1) if m else ""))
    return out


def main():
    pali = open(PALI_FILE, encoding="utf-8").read().rstrip("\n").split("\n")
    idx = pali.index(START)
    assert pali[idx - 1] == ""
    head_nonempty = [l for l in pali[:idx] if l.strip()]
    sample = open(SAMPLE_FILE, encoding="utf-8", newline="").read()
    assert sample.endswith("\n") and "\r" not in sample
    assert len(head_nonempty) == 77 == len([l for l in sample.split("\n") if l.strip()])
    rest = translate_rest(pali[idx:])
    text = sample + "\n" + "\n".join(rest).rstrip("\n") + "\n"
    with open(OUT_FILE, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    assert open(OUT_FILE, encoding="utf-8", newline="").read().startswith(sample)
    print("OK:", OUT_FILE, "|", len([l for l in text.split("\n") if l.strip()]), "non-empty lines")
    if "--unused" in sys.argv:
        print("unused surfaces:", sorted(UNUSED))


if __name__ == "__main__":
    main()
