"""viññāṇa: चेतना (feminine) -> विज्ञान (masculine) in the Hindi pi-1 text, with gender agreement.

Every Hindi चेतना in pi-1 renders viññāṇa (checked: all 43 termbase entries with चेतना are viññāṇa
entries; cetanā is इरादा). Used as a module by fix_pi1_hi.py: convert(text) -> (text, log).
"""
import re

POSTP = r"(?:का|के|की|से|में|को|पर|तक|द्वारा|वाला|वाले|वाली|रूपी)"
GEN_FEM = r"(की|अपनी|उसकी|उनकी|इसकी|इनकी|जिसकी|जिनकी)"
MASC = {"की": "का", "अपनी": "अपना", "उसकी": "उसका", "उनकी": "उनका", "इसकी": "इसका", "इनकी": "इनका",
        "जिसकी": "जिसका", "जिनकी": "जिनका"}
OBL = {"की": "के", "अपनी": "अपने", "उसकी": "उसके", "उनकी": "उनके", "इसकी": "इसके", "इनकी": "इनके",
       "जिसकी": "जिसके", "जिनकी": "जिनके"}


L = r"ऀ-ॣॱ-ॿ"  # Devanagari letters and signs (not danda, not digits)


def convert(t):
    log = {}

    def sub(pat, rep, s, key):
        new, n = re.subn(pat, rep, s)
        log[key] = log.get(key, 0) + n
        return new

    # plurals first
    t = sub(GEN_FEM + r" चेतनाओं", lambda m: OBL[m.group(1)] + " विज्ञानों", t, "की चेतनाओं → के विज्ञानों")
    t = sub(r"चेतनाओं", "विज्ञानों", t, "चेतनाओं→विज्ञानों")
    t = sub(r"(होने )वाली (आँख|कान|नाक|जीभ|शरीर|मन) की चेतना", r"\1वाला \2 का विज्ञान", t, "होने वाली X की चेतना → होने वाला X का विज्ञान")
    t = sub(r"इंद्रिय-चेतनाएँ", "इंद्रिय-विज्ञान", t, "इंद्रिय-चेतनाएँ→इंद्रिय-विज्ञान")
    t = sub(r"चेतनाएँ", "विज्ञान", t, "चेतनाएँ→विज्ञान")
    t = sub(r"इंद्रिय-चेतना(?![ऀ-ॣॱ-ॿ])", "इंद्रिय-विज्ञान", t, "इंद्रिय-चेतना→इंद्रिय-विज्ञान")
    # genitive before the noun: oblique (followed by a postposition) or direct
    t = sub(GEN_FEM + r" चेतना(?= " + POSTP + r"(?![" + L + r"]))", lambda m: OBL[m.group(1)] + " विज्ञान", t,
            "की चेतना + postposition → के विज्ञान")
    t = sub(GEN_FEM + r" चेतना(?![" + L + r"])", lambda m: MASC[m.group(1)] + " विज्ञान", t, "की चेतना → का विज्ञान")
    # the noun itself
    t = sub(r"(?<![" + L + r"-])चेतना(?![" + L + r"])", "विज्ञान", t, "चेतना → विज्ञान")
    # the arising series after the noun (with or without ", X के सहारे,")
    t = sub(r"(विज्ञान(?:, [^,]{1,25} के सहारे,)? उत्पन्न हो )चुक[ाी]( है, उत्पन्न हो)ती( है, उत्पन्न हो)गी( या उत्पन्न हो सक)ती",
            r"\1चुका\2ता\3गा\4ता", t, "arising series after विज्ञान → masculine")
    # relative clause about the noun: "विज्ञान उत्पन्न होता है, जो X के साथ होने वाली है"
    t = sub(r"(विज्ञान उत्पन्न हो(?:ता|ती) है, जो [^,]{1,20} के साथ होने )वाली है", r"\1वाला है", t,
            "जो … के साथ होने वाली है → वाला है")
    # verb agreement right after the noun (subject)
    for f, m_ in [("उत्पन्न होती है", "उत्पन्न होता है"), ("उत्पन्न हो चुकी", "उत्पन्न हो चुका"),
                  ("उत्पन्न होगी", "उत्पन्न होगा"), ("उत्पन्न हुई", "उत्पन्न हुआ"), ("उत्पन्न नहीं हुई", "उत्पन्न नहीं हुआ"),
                  ("उत्पन्न होने वाली", "उत्पन्न होने वाला"), ("उत्पन्न न हुई", "उत्पन्न न हुआ"),
                  ("होती है", "होता है"), ("क्या होती है", "क्या होता है")]:
        t = sub(r"विज्ञान " + f, "विज्ञान " + m_, t, f"विज्ञान {f} → {m_}")
    return t, log


FEM_NEAR = re.compile(r"विज्ञान(?:ों)?[^।;?\n]{0,40}?(?<![ऀ-ॿ])(होती|हुई|चुकी|वाली|रही|गई|सकती|जाती|उत्पन्न होती)(?![ऀ-ॿ])")
