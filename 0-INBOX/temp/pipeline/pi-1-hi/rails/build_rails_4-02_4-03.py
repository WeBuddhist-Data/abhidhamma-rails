    body = seg.split("? ", 1)[1].split(" – ime dhammā")[0]
    out = []
    for item in body.split(", "):
        parts = item.split()
        x, y = parts[0].lower(), parts[1].lower()
        hx, gen = table[x]
        hy = instr[y]
        out.append(f"{hx} {hy} के साथ {tail_of(gen)}")
    return ", ".join(out)


