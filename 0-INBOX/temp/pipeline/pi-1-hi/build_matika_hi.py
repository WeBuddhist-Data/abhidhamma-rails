def V(kind, sigla, text):
    """Variant bracket: kind 'p' = पाठभेद (a word differs), 's' = वर्तनी-भेद (spelling only)."""
    label = "पाठभेद" if kind == "p" else "वर्तनी-भेद"
    return f" [{label} ({sigla}): {text}]"


def it(q, var=""):
    """'<qualifier> परिघटनाएँ।' with an optional variant bracket after the qualifier (pi-3 placement)."""
    return f"{q}{var} {P}{DANDA}"


