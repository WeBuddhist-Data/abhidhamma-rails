ID = re.compile(r"\s*\^([0-9A-Za-z-]+)\s*$")
BRACKET = re.compile(r" \[[^\]]*\]")


def bare(hi):
    """Item name without variant bracket and without the final danda."""
    return BRACKET.sub("", hi).rstrip(DANDA).strip()


def QUESTION(name):
    """'Katame dhammā X?' with X named as in the matrix (bare name)."""
    if name.startswith(NOT_REL):
        return "कौन-सी परिघटनाएँ " + name[len(NOT_REL):] + "?"
    return f"{name} कौन-सी हैं?"


def ANSWER_BARE(name):
    """'ime dhammā X' (no final danda)."""
    if name.startswith(NOT_REL):
        return "ये परिघटनाएँ " + name[len(NOT_REL):]
    return f"ये {name} हैं"


def ANSWER(name):
    return ANSWER_BARE(name) + DANDA


def pali_segments():
    segs, buf = [], []
    for line in PALI.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        m = ID.search(line)
        if m:
            buf.append(line[:m.start()])
            segs.append((m.group(1), buf))
            buf = []
        else:
            buf.append(line)
    assert not buf, "trailing lines without id"
    return segs


def hindi_segment(bid):
    if bid == "1-M-0":
        return [H_MATIKA]
    if bid == "1-M-1-0":
        return [H_TIKA]
    if bid == "1-M-2-0":
        return [H_DUKA]
    if bid in GROUPS:
        return [GROUPS[bid][0]]
    m = re.fullmatch(r"1-M([12])-(\d+)", bid)
    assert m, bid
    items = (TRIADS if m.group(1) == "1" else PAIRS)[int(m.group(2))]
    lines = [f"({LETTERS[i]}) {t}" for i, t in enumerate(items)]
    return lines + TAILS.get(bid, [])


MATRIX_ITEMS_HI = []  # (block id, letter, pali, hindi)
BARE = {}


def build():
    out = []
    for bid, plines in pali_segments():
        hlines = hindi_segment(bid)
        assert len(hlines) == len(plines), (bid, plines, hlines)
        for p, h in zip(plines, hlines):
            assert ("[" in p) == ("[" in h), (bid, p, h)
            assert p.startswith("#") == h.startswith("#"), (bid, p, h)
            if p.startswith("#"):
                assert len(p) - len(p.lstrip("#")) == len(h) - len(h.lstrip("#")), (bid, p, h)
            for i, pl in enumerate(PALI_LETTERS):
                if p.startswith(pl + " "):
                    pref = f"({LETTERS[i]}) "
                    assert h.startswith(pref), (bid, p, h)
                    hi = h[len(pref):]
                    MATRIX_ITEMS_HI.append((bid, LETTERS[i], p[len(pl) + 1:], hi))
                    BARE[(bid, LETTERS[i])] = bare(hi)
        hlines = hlines[:-1] + [hlines[-1] + f" ^{bid}"]
        out.append("\n".join(hlines))
    return "\n\n".join(out) + "\n"


TEXT = build()
assert len(MATRIX_ITEMS_HI) == 22 * 3 + 142 * 2, len(MATRIX_ITEMS_HI)
assert "–" not in TEXT and "—" not in TEXT and ":-" not in TEXT

