def group(r, p, pron, with_e=True):
    """The pairs of a group (taints, fetters, ...), in the pi-3 wording.
    r: 'बंधन रूपी' (being one of them); p: 'बंधनों' (them, oblique); pron: 'उनका' / 'उसका'."""
    g = [
        [it(r), it(f"{r} न होने वाली")],
        [it(f"{p} का विषय बनने वाली"), it(f"{p} का विषय न बनने वाली")],
        [it(f"{p} से जुड़ी"), it(f"{p} से अलग")],
        [it(f"{r} भी और {p} का विषय बनने वाली भी"), it(f"{p} का विषय बनने वाली, पर स्वयं {r} न होने वाली")],
    ]
    if with_e:
        g.append([it(f"{r} भी और {p} से जुड़ी भी"), it(f"{p} से जुड़ी, पर स्वयं {r} न होने वाली")])
    g.append([it(f"{p} से अलग, पर {pron} विषय बनने वाली"), it(f"{p} से अलग और {pron} विषय न बनने वाली")])
    return g


