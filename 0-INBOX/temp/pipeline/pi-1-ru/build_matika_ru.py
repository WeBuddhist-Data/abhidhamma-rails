def group(ins, sub, nsub, with_e=True):
    """The pairs of a group (taints, fetters, ...), in the pi-3 wording.
    ins: the group noun, instrumental plural ('влечениями');
    sub / nsub: (participle, short form) for -niya / a-…-niya ('подверженные влечениям', 'подвержены влечениям')."""
    g = [
        [P(f"являющиеся {ins}", f"являются {ins}"), P(f"не являющиеся {ins}", f"не являются {ins}")],
        [P(*sub), P(*nsub)],
        [P(f"связанные с {ins}", f"связаны с {ins}"), P(f"не связанные с {ins}", f"не связаны с {ins}")],
        [R(f"являются {ins} и {sub[1]}"), R(f"{sub[1]}, но сами не являются {ins}")],
    ]
    if with_e:
        g.append([R(f"являются {ins} и связаны с {ins}"), R(f"связаны с {ins}, но сами не являются {ins}")])
    g.append([R(f"не связаны с {ins}, но {sub[1]}"), R(f"не связаны с {ins} и {nsub[1]}")])
    return g


def subj(dat):
    """'подверженные X' / 'не подверженные X' (X dative plural)."""
    return (f"подверженные {dat}", f"подвержены {dat}"), (f"не подверженные {dat}", f"не подвержены {dat}")


