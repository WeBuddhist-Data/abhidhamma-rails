SLOT = "{V}"  # where a variant bracket goes inside an item name


class Item:
    """nom: the item name (lower-case start) with an optional SLOT for the variant bracket;
    pred: what follows «Какие явления …?» in the question frame (None: no question form)."""

    def __init__(self, nom, pred, var=""):
        if SLOT not in nom:
            nom += SLOT
        self.nom, self.pred, self.var = nom, pred, var

    def v(self, kind, sigla, text):
        return Item(self.nom, self.pred, V(kind, sigla, text))

    @property
    def bare(self):
        return self.nom.replace(SLOT, "")

    @property
    def line(self):
        t = self.nom.replace(SLOT, self.var)
        return t[0].upper() + t[1:] + "."


def A(adj, ins, pred=None):
    """adjective before «явления»: «благие явления»; question «являются благими»."""
    return Item(f"{adj}{SLOT} явления", pred or f"являются {ins}")


def P(post, pred):
    """qualifier after «явления»: «явления, связанные с …»; pred is the short/verbal form."""
    return Item(f"явления, {post}", pred)


def W(prep, pred):
    """prepositional qualifier after «явления», no comma: «явления с направленной мыслью»."""
    return Item(f"явления {prep}", pred)


def R(clause):
    """relative clause: «явления, которые …»; the clause itself is the question predicate."""
    return Item(f"явления, которые {clause}", clause)


def NOUN(text):
    """discourse pairs ^1-M2-109 ff.: a bare noun phrase, no «явления», no question frame."""
    return Item(text, None)


