def pali_segments(path):
    segs, buf = [], []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        m = ID.search(line)
        if m:
            buf.append(line[:m.start()])
            segs.append((m.group(1), buf))
            buf = []
        else:
            buf.append(line)
    assert not buf
    return segs


def dashes(t):
    return t.count("–") + t.count("—")


def build(part, fn):
    psegs = pali_segments(PALI_DIR / part)
    P = dict(psegs)
    segs = fn(P)
    assert [b for b, _ in segs] == [b for b, _ in psegs], (
        part, [(a, b) for (a, _), (b, _) in zip(segs, psegs) if a != b][:3])
    out = []
    for (bid, rl), (_, pl) in zip(segs, psegs):
        assert len(rl) == len(pl), (bid, len(rl), len(pl))
        for r, p in zip(rl, pl):
            assert dashes(r) == dashes(p), (bid, dashes(p), dashes(r), r)
            assert p.startswith("#") == r.startswith("#"), bid
            assert ("[" in p) == ("[" in r), (bid, r)
            assert "—" not in r and ":-" not in r and "  " not in r, (bid, r)
            assert not re.search(r"(?<![А-Яа-яЁё])ли(?![А-Яа-яЁё])", r), (bid, r)
            body = re.sub(r"\[[^\]]*\]", "", r)
            assert not re.search(r"[A-Za-zÀ-ɏḀ-ỿ]", body), (bid, r)
            assert ".." not in r.replace("…", ""), (bid, r)
        rl = rl[:-1] + [rl[-1] + f" ^{bid}"]
        out.append("\n".join(rl))
    return "\n\n".join(out) + "\n", len(segs)


