def _doors(guarded):
    """indriyesu (a)guttadvāratā body (pi-4 ^4-57 / ^4-77)."""
    ne = "" if guarded else "не "
    grasp = ("не цепляется за её общий облик, не цепляется за её детали" if guarded
             else "цепляется за её общий облик, цепляется за её детали")
    grasp_m = grasp.replace("её", "его")
    tail = (f"он {ne}старается обуздать способность {{x}}, из-за необузданности которой в него могли бы проникнуть "
            f"алчность и уныние, дурные неблагие явления, {ne}охраняет способность {{x}}, {ne}соблюдает "
            f"сдержанность в отношении способности {{x}}.")
    return (f"Есть человек, который, увидев глазом видимую форму, {grasp}; {tail.format(x='глаза')} "
            f"Услышав ухом звук… понюхав носом запах… попробовав языком вкус… коснувшись телом осязаемого… "
            f"познав умом объект ума, {grasp_m}; {tail.format(x='ума')}")


