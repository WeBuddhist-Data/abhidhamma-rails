# ---- the "A with B is both X and X-associated" lists -------------------------------------------------
GENDER_SHORT = {"m": "связан", "f": "связана", "n": "связано"}


def both_list(pali_line, nom, ins, gen, ceva):
    """Build «A вместе с B является X и связан(а/о) с X» items from the Pāli, in the Pāli order.
    nom: Pāli nominative -> (Russian nominative, gender); ins: Pāli instrumental -> Russian instrumental;
    ceva: the Russian «является X и связан… с X» noun pair (instrumental singular)."""
    body = pali_line.split("? ", 1)[1].split(f" {D} ime dhammā", 1)[0]
    out = []
    for item in body.split(", "):
        a, b = item.split(" ")[:2]
        r_nom, g = nom[a[0].lower() + a[1:]]
        prep = "со" if ins[b].startswith("злоб") else "с"   # «вместе со злобой»
        out.append(f"{r_nom} вместе {prep} {ins[b]} является {ceva} и {GENDER_SHORT[g]} с {ceva}")
    return cap(", ".join(out))


