def plane(p):
    """'X-bhūmiyaṃ' -> «На уровне X»; 'Na X-bhūmiyaṃ' -> «На уровне, отличном от уровня X»."""
    return f"На уровне, отличном от уровня {p[3:]}" if p.startswith("na ") else f"На уровне {p}"


def bhumi_with(k, p, factor_gen, pron, aggs, loc=LOC3):
    """'X-bhūmiyaṃ kāmāvacare … , Y ṭhapetvā, taṃsampayutto … – ime dhammā X.'"""
    return (f"{Q(k)} {plane(p)}, {loc}, за исключением {factor_gen}, связанная с {pron} {aggs} "
            f"{ans(k)}")


def bhumi_without(k, p, factor_nom, loc=LOC4, sep=";"):
    """'Na/A-X-bhūmiyaṃ kāmāvacare …; vedanākkhandho…pe… viññāṇakkhandho; Y ca, sabbañca rūpaṃ, … – …'"""
    return f"{Q(k)} {plane(p)}, {loc}: {VED}{sep} {factor_nom}, {ALLRUPA} {ans(k)}"


