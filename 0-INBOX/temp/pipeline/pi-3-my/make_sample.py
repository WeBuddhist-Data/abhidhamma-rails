"""Burmese zero-shot sample of pi-3 (Dhātukathā, «ဓာတ်များအကြောင်း ဆွေးနွေးခြင်း»): preamble, 1-uddeso, 2-pathamanayo.

usage: python3 -I -X utf8 make_sample.py [chapter ...] [--terms]
Every line is generated from the Pāli by my3_formulas.translate_line() through the frames and tables of
my3_formulas.py (which reads the FINAL pi-1 / pi-2 Burmese, read only); a sentence no frame or table entry matches
stops the run (my3_formulas.Miss), nothing is guessed. A chapter is written only when every line passed; on a stop the
lines that passed go to scratch/partial-<chapter> and the failing line is printed. --terms (also by default with no
chapter argument) rewrites my3-zeroshot-terms.md from the tables.
Model for later chapters: copy this file, add your entries to the tables of my3_formulas (or a tables module), frames
to F.EXTRA_RULES; change NAMES_OUT.
"""
import pathlib
import sys
import unicodedata

sys.dont_write_bytecode = True
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import my3_formulas as F  # noqa: E402

ROOT = HERE.parents[3]
PALI = ROOT / "AI_translation/pali/pi-3_split_chapters"
OUT = ROOT / "AI_translation/burmese/pi-3-burmese-plain-zeroshot_split_chapters"
NAMES_OUT = ["preamble.md", "1-uddeso.md", "2-pathamanayo.md"]


def write(name, txt):
    txt = unicodedata.normalize("NFC", txt)
    (OUT / name).write_text(txt, encoding="utf-8")
    print(f"wrote {name}: {sum(1 for l in txt.splitlines() if l)} lines")


def chapter(name):
    lines = (PALI / name).read_text(encoding="utf-8-sig").splitlines()
    done = []
    bid_of = {}
    cur = []
    for i, line in enumerate(lines):          # block ID of each line = the ID that closes its segment
        if line.strip():
            cur.append(i)
            m = F.ID_RE.search(line)
            if m:
                for j in cur:
                    bid_of[j] = m.group(1)
                cur = []
    for i, line in enumerate(lines):
        try:
            done.append(F.translate_line(line, bid_of.get(i)))
        except F.Miss as e:
            part = HERE / "scratch" / ("partial-" + name)
            part.parent.mkdir(exist_ok=True)
            part.write_text("\n".join(done) + "\n", encoding="utf-8")
            print(f"STOP {name} line {i + 1}: {e}\n  {line[:200]}\n  ({len(done)} lines kept in {part})")
            return False
    write(name, "\n".join(done).rstrip("\n") + "\n")
    return True


